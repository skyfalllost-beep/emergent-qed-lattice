def _mixed_gaussian_resolvent_fock_check():
    """Independent truncated-Fock checks of mixed two- and three-link kernels."""
    from scipy.linalg import expm
    from scipy.special import roots_laguerre
    from scipy.integrate import quad
    size=12;ann=np.diag(np.sqrt(np.arange(1,size)),1);X=ann+ann.T
    omega=np.array([.7,2.3]);eta=np.array([[.10,.03],[-.06,.11],[.08,-.05]])
    W=[np.kron(expm(1j*x*X),expm(1j*y*X)) for x,y in eta]
    E=np.array([omega[0]*i+omega[1]*j for i in range(size) for j in range(size)])
    d1,d2=36.,88.
    direct=W[2][0]@((W[1]@(W[0][:,0]/(d1+E)))/(d2+E))
    S=(eta**2).sum(1);x,v=roots_laguerre(24);t1=x/d1;t2=x/d2
    c12=np.exp(-t1[:,None]*omega)@(eta[0]*eta[1])
    c23=np.exp(-t2[:,None]*omega)@(eta[1]*eta[2])
    c13=np.einsum('ig,jg,g->ij',np.exp(-t1[:,None]*omega),
                  np.exp(-t2[:,None]*omega),eta[0]*eta[2])
    integral=np.exp(-S.sum()/2)*(v@np.exp(-c12[:,None]-c23[None,:]-c13)@v)/(d1*d2)
    inv=np.divide(1,E,out=np.zeros_like(E),where=E>0)
    direct2=W[1][0]@(inv*W[0][:,0])
    integral2=np.exp(-(S[0]+S[1])/2)*quad(
        lambda t:np.expm1(-np.dot(eta[0]*eta[1],np.exp(-omega*t))),0,100,epsabs=1e-14)[0]
    errors=[float(abs(direct-integral)),float(abs(direct2-integral2))]
    assert max(errors)<1e-12
    return dict(oscillator_cutoff=size,dimension=size**2,
        three_displacement_two_resolvent_error=errors[0],
        vacuum_subtracted_two_displacement_error=errors[1])


def native_gaussian_effective_matrices(return_context=False):
    """Complete order J^2 and leading interlayer J^3 within the frozen setup.

    P is the 48 lowest endpoint positions with zero positive-frequency photons.
    The same L4 noncompact regulator, fixed f=1 and fixed layered q0 are used.
    Include all intermediate charge time orders and all positive Gaussian
    photons relevant at these orders. A remote compensator is understood;
    the periodic pseudoinverse regulates Coulomb differences as in section 38.
    Intralayer order J^3, background relaxation, global zero modes and compact
    effects are not supplied. The 24-band truncation below is not a full
    third-order Hamiltonian and is not used to certify a corrected Weyl root.
    """
    from collections import Counter
    from functools import lru_cache
    from itertools import permutations
    from scipy.special import roots_laguerre
    from scipy.integrate import quad
    c=_native_single_charge_host();lay,q,G,core=c['lay'],c['q'],c['G'],c['core']
    phi=G@q;P=np.flatnonzero(c['single'][1]==54);pindex={int(p):i for i,p in enumerate(P)}
    nl=len(lay['links']);curl=np.zeros((len(lay['triangles'])+len(lay['squares']),nl))
    for i,cycle in enumerate(lay['triangles']+lay['squares']):
        for ell,sign in cycle:curl[i,ell]+=sign
    val,vec=np.linalg.eigh(curl.T@curl);selected=val>1e-9
    frequency=np.sqrt(val[selected])  # U*K=1 for the current parameters
    eta=vec[:,selected]*np.sqrt(.1/frequency)[None,:]
    keys,group=np.unique(np.round(frequency,11),return_inverse=True)
    omega=np.array([np.mean(frequency[group==i]) for i in range(len(keys))])
    S=np.sum(eta**2,axis=1)
    kinds=np.array([int(a//2==b//2) for v,a,b in lay['links']])
    _,fourier_weights=_native_transverse_mode_weights(4)
    variance_error=float(np.max(abs(S-fourier_weights.sum(axis=1)[kinds])))
    assert len(frequency)==766 and len(omega)==13 and variance_error<1e-13
    @lru_cache(None)
    def correlation_weights(l,m):
        return np.bincount(group,weights=eta[l]*eta[m],minlength=len(omega))
    quadratures={n:roots_laguerre(n) for n in (12,20,24,32)}
    @lru_cache(None)
    def kernel2(l,m,direction_product,delta,excited_only=False,order=20):
        v=correlation_weights(l,m);pref=np.exp(-(S[l]+S[m])/2)
        if excited_only:
            assert abs(delta)<1e-10
            # Subtract the transverse vacuum: it is already in retained P.
            # expm1 avoids cancellation when the correlation decays to zero.
            return pref*quad(lambda t:np.expm1(-direction_product*np.dot(v,np.exp(-omega*t))),
                             0,40/min(omega),epsabs=1e-13,epsrel=1e-12)[0]
        assert delta>0
        x,weights=quadratures[order]
        corr=np.exp(-x[:,None]*omega[None,:]/delta)@v
        return float(pref*(weights@np.exp(-direction_product*corr))/delta)
    def kernel3(links,directions,gaps,order=12):
        x,weights=quadratures[order];t1=x/gaps[0];t2=x/gaps[1]
        exp1=np.exp(-t1[:,None]*omega);exp2=np.exp(-t2[:,None]*omega)
        c12=exp1@correlation_weights(links[0],links[1])
        c23=exp2@correlation_weights(links[1],links[2])
        c13=np.einsum('ig,jg,g->ij',exp1,exp2,correlation_weights(links[0],links[2]))
        s1,s2,s3=directions
        f=np.exp(-s1*s2*c12[:,None]-s2*s3*c23[None,:]-s1*s3*c13)
        return float(np.exp(-sum(S[links])/2)*(weights@f@weights)/np.prod(gaps))
    adjacency=[[] for _ in q]
    for ell,(i,j) in enumerate(lay['endpoints']):
        adjacency[i].append((j,ell,1));adjacency[j].append((i,ell,-1))
    ops=[lay['geo']['embed'](v,a,b) for v,a,b in lay['links']]
    # Cubic original graph has no triangles. Every three-hop closed walk of
    # its line graph is a port triangle at one original vertex. Its Gamma
    # product is purely imaginary, so the reverse Hermitian path cancels it
    # when multiplied by the real Gaussian resolvent weight.
    closed_triangle_checks=0
    for cycle in lay['triangles']:
        product_op=(1,0,0);reverse_op=(1,0,0)
        for ell,sgn in cycle:product_op=multiply(ops[ell],product_op)
        for ell,sgn in reversed(cycle):reverse_op=multiply(ops[ell],reverse_op)
        assert product_op[1:]==(0,0) and reverse_op[1:]==(0,0)
        assert complex(product_op[0]) in (1j,-1j)
        assert reverse_op[0]==complex(product_op[0]).conjugate()
        closed_triangle_checks+=1
    assert closed_triangle_checks==1280
    def order_sign(l,m):
        x,y=ops[l],ops[m]
        return (-1)**((x[1]&y[2]).bit_count()+(x[2]&y[1]).bit_count())
    def excitation_energy(ch,p):
        indices=list(ch);values=np.array(list(ch.values()))
        return (core(ch)-54+.2*sum(phi[x]*d for x,d in ch.items())
                +.1*(values@G[np.ix_(indices,indices)]@values-G[p,p]))
    # Every return, including the host's high-charge positions and excited
    # photons through its low positions. Subtract the dressed background.
    background=0.
    for l,(i,j) in enumerate(lay['endpoints']):
        for s,t in ((i,j),(j,i)):
            gap=core({s:-1,t:1})+.2*(phi[t]-phi[s])+.1*(G[s,s]+G[t,t]-2*G[s,t])
            background-=kernel2(l,l,-1,float(gap))
    diagonal=[];return_counts=Counter()
    for p in P:
        total=0.
        for l,(i,j) in enumerate(lay['endpoints']):
            for s,t in ((i,j),(j,i)):
                ch={int(p):1};ch[s]=ch.get(s,0)-1;ch[t]=ch.get(t,0)+1
                ch={x:d for x,d in ch.items() if d}
                excited=s==p and t in pindex
                delta=0. if excited else float(excitation_energy(ch,p))
                total-=kernel2(l,l,-1,delta,excited)
                category='P_charge_excited_photons' if excited else ('high_host_charge' if s==p else 'outside_host_charge')
                return_counts[category]+=1
        diagonal.append(total-background)
    diagonal=np.array(diagonal)
    # Two-hop off-diagonal paths have a host ordering and a reversed ordering
    # with an extra pair. Their Gamma products may differ by a minus sign.
    records2=[];counts=Counter();kernel2_error=0.
    for p in P:
        for aa,l1,s1 in adjacency[p]:
            for r,l2,s2 in adjacency[aa]:
                if r not in pindex or r==p:continue
                excited=aa in pindex
                dp=0. if excited else float(excitation_energy({int(aa):1},p))
                dm=float(excitation_energy({int(p):1,int(r):1,int(aa):-1},p))
                ih=kernel2(l1,l2,s1*s2,dp,excited)
                im=kernel2(l1,l2,s1*s2,dm);sign=order_sign(l1,l2)
                # Check the sign directly using full Pauli products.
                direct=multiply(ops[l2],ops[l1]);reverse=multiply(ops[l1],ops[l2])
                assert direct[1:]==reverse[1:] and reverse[0]==sign*direct[0]
                fine_m=kernel2(l1,l2,s1*s2,dm,False,32)
                fine_h=ih if excited else kernel2(l1,l2,s1*s2,dp,False,32)
                kernel2_error=max(kernel2_error,abs(im-fine_m),abs(ih-fine_h))
                phase=c['u'][r,aa]*c['u'][aa,p]
                translation=s1*c['translations'][l1]+s2*c['translations'][l2]
                records2.append((pindex[r],pindex[int(p)],translation,-phase*(ih+sign*im)))
