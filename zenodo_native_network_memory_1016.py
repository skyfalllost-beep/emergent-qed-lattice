from itertools import combinations, product
import json
import numpy as np


I = np.eye(2, dtype=complex)
X = np.array([[0, 1], [1, 0]], dtype=complex)
Y = np.array([[0, -1j], [1j, 0]], dtype=complex)
Z = np.diag([1., -1.]).astype(complex)
PAULI = [I, X, Y, Z]


def kron_all(matrices):
    result = np.array([[1]], dtype=complex)
    for matrix in matrices:
        result = np.kron(result, matrix)
    return result


def make_local_gamma():
    """Six Clifford generators, restricted to even three-qubit parity."""
    majorana = [kron_all([Z] * k + [a] + [I] * (2-k))
                for k in range(3) for a in [X, Y]]
    even = [0, 3, 5, 6]
    matrices, local = {}, {}
    for a, b in combinations(range(6), 2):
        matrix = (1j * majorana[a] @ majorana[b])[np.ix_(even, even)]
        matrices[a, b], matrices[b, a] = matrix, -matrix
        for labels in product(range(4), repeat=2):
            pauli = kron_all([PAULI[p] for p in labels])
            coefficient = np.trace(pauli.conj().T @ matrix) / 4
            if abs(coefficient) > .5:
                assert np.array_equal(coefficient * pauli, matrix)
                local[a, b] = (complex(coefficient), labels)
                local[b, a] = (-complex(coefficient), labels)
    operators = [np.eye(4)] + [matrices[a, b] for a, b in combinations(range(6), 2)]
    gram = np.array([[np.trace(a.conj().T @ b) for b in operators] for a in operators])
    assert np.array_equal(gram, 4 * np.eye(16))
    for a, b, c in product(range(6), repeat=3):
        if len({a, b, c}) == 3:
            assert np.array_equal(matrices[a, b] @ matrices[b, c], 1j * matrices[a, c])
    return local


LOCAL = make_local_gamma()


def multiply(left, right):
    """Exact signed Pauli product, represented as coefficient * X^x Z^z."""
    c, x, z = left
    d, y, w = right
    return c * d * (-1 if (z & y).bit_count() % 2 else 1), x ^ y, z ^ w


def anticommutes(left, right):
    return ((left[1] & right[2]).bit_count() + (left[2] & right[1]).bit_count()) % 2


def signed_basis(operators, n):
    """Row reduction tracks phases; -I flags an inconsistent all-plus sector."""
    basis, minus_identity = {}, False
    for operator in operators:
        p = operator
        while p[1] or p[2]:
            key = (p[1] | (p[2] << n)).bit_length() - 1
            if key not in basis:
                basis[key] = p
                break
            p = multiply(p, basis[key])
        else:
            assert p[0] in (1, -1)
            minus_identity |= p[0] == -1
    return basis, minus_identity


def solve_binary(rows, rhs, n):
    equations = [int(row) | (int(b) << n) for row, b in zip(rows, rhs)]
    pivots, mask = {}, (1 << n) - 1
    for equation in equations:
        while equation & mask:
            key = (equation & mask).bit_length() - 1
            if key not in pivots:
                pivots[key] = equation
                break
            equation ^= pivots[key]
        else:
            assert not (equation >> n) & 1, 'Inconsistent symplectic equations'
    solution = 0
    for key in sorted(pivots):
        equation = pivots[key]
        value = ((equation >> n) & 1) ^ ((equation & mask & solution).bit_count() % 2)
        if value:
            solution |= 1 << key
    assert all((row & solution).bit_count() % 2 == b for row, b in zip(rows, rhs))
    return solution


def audit(L, return_geometry=False):
    assert L >= 3
    vertices = list(product(range(L), repeat=3))
    ids = {vertex: i for i, vertex in enumerate(vertices)}
    n = 2 * len(vertices)

    def shift(vertex, axis, step=1):
        v = list(vertex)
        v[axis] = (v[axis] + step) % L
        return tuple(v)

    def embed(vertex, a, b):
        coefficient, labels = LOCAL[a, b]
        x = z = 0
        for k, label in enumerate(labels):
            bit = 1 << (2 * ids[vertex] + k)
            if label in (1, 2):
                x |= bit
            if label in (2, 3):
                z |= bit
            if label == 2:
                coefficient *= 1j
        return coefficient, x, z

    def plaquette(vertex, a, b):
        va, vb = shift(vertex, a), shift(vertex, b)
        vab = shift(va, b)
        p = (1, 0, 0)
        # At each corner: direction to previous vertex, direction to next vertex.
        for factor in [embed(vertex, 2*b, 2*a), embed(va, 2*a+1, 2*b),
                       embed(vab, 2*b+1, 2*a+1), embed(vb, 2*a, 2*b+1)]:
            p = multiply(p, factor)
        return p

    faces = {(v, a, b): plaquette(v, a, b)
             for v in vertices for a, b in combinations(range(3), 2)}
    stabilizers = list(faces.values())
    assert all(not anticommutes(f, g) for f, g in combinations(stabilizers, 2))
    assert all(multiply(f, f) == (1, 0, 0) for f in stabilizers)
    for vertex in vertices:
        p = (1, 0, 0)
        for a, b in combinations(range(3), 2):
            p = multiply(p, faces[vertex, a, b])
            p = multiply(p, faces[shift(vertex, 3-a-b), a, b])
        assert p == (1, 0, 0), 'Cube relation failed'

    basis, inconsistent = signed_basis(stabilizers, n)
    plane_signs = []
    for a, b in combinations(range(3), 2):
        p = (1, 0, 0)
        for vertex in vertices:
            if vertex[3-a-b] == 0:
                p = multiply(p, faces[vertex, a, b])
        assert p[1:] == (0, 0) and p[0] in (1, -1)
        plane_signs.append(int(p[0].real))

    result = dict(L=L, vertices=len(vertices), physical_qubits=n,
                  plaquettes=len(stabilizers), stabilizer_rank=len(basis),
                  all_plus_sector_exists=not inconsistent, plane_product_signs=plane_signs)
    if inconsistent:
        result['all_plus_dimension'] = 0
        result['actual_ground_dimension'] = 'not computed for frustrated boundary sample'
        return result

    origin = (0, 0, 0)
    flips = {f'{a},{b}': sum(anticommutes(embed(origin, a, b), f) for f in stabilizers)
             for a, b in combinations(range(6), 2)}
    assert all(count > 0 for count in flips.values())
    result.update(all_plus_dimension=2 ** (n-len(basis)), local_gamma_flips=flips)

    loops = []
    for axis in range(3):
        p = (1, 0, 0)
        for j in range(L):
            v = [0, 0, 0]
            v[axis] = j
            p = multiply(p, embed(tuple(v), 2*axis, 2*axis+1))
        loops.append(p)
    assert all(not anticommutes(w, f) for w in loops for f in stabilizers)
    assert all(not anticommutes(w, v) for w, v in combinations(loops, 2))
    extended_basis, inconsistent_loops = signed_basis(stabilizers + loops, n)
    assert not inconsistent_loops
    result['rank_with_three_loops'] = len(extended_basis)

    # An explicit winding x loop made only from perpendicular-port factors.
    assert L % 2 == 0, 'This staircase construction is specified for even L'
    position, path = origin, []
    for axis, sign in [(0, 1), (1, 1), (0, 1), (1, -1)] * (L//2):
        path.append((position, 2*axis + int(sign < 0)))
        position = shift(position, axis, sign)
    assert position == origin
    winding = (1, 0, 0)
    generators = []
    for j, (vertex, outgoing) in enumerate(path):
        incoming = path[(j-1) % len(path)][1] ^ 1
        assert incoming//2 != outgoing//2
        generator = embed(vertex, incoming, outgoing)
        generators.append(generator)
        winding = multiply(winding, generator)
    assert all(not anticommutes(winding, f) for f in stabilizers)
    difference = multiply(winding, loops[0])
    while difference[1] or difference[2]:
        key = (difference[1] | (difference[2] << n)).bit_length() - 1
        assert key in basis, 'Winding operator differs from W_x beyond stabilizers'
        difference = multiply(difference, basis[key])
    assert difference == (1, 0, 0)
    result['native_perpendicular_loop'] = dict(local_factors=len(path), equals_Wx_on_code=True)

    # Solve for one conjugate operator per global loop; no minimal-weight claim.
    rows = [p[2] | (p[1] << n) for p in stabilizers + loops]
    supports = []
    conjugates = []
    for k in range(3):
        rhs = [0] * len(stabilizers) + [int(j == k) for j in range(3)]
        vector = solve_binary(rows, rhs, 2*n)
        x, z = vector & ((1 << n)-1), vector >> n
        p = ((1j) ** ((x & z).bit_count()), x, z)
        assert multiply(p, p) == (1, 0, 0)
        assert all(not anticommutes(p, f) for f in stabilizers)
        assert [anticommutes(p, w) for w in loops] == rhs[-3:]
        conjugates.append(p)
        supports.append(dict(qubit_factors=(x | z).bit_count(),
                             nodes=sum(bool(((x | z) >> (2*i)) & 3)
                                       for i in range(len(vertices)))))
    result['conjugate_operator_supports_not_minimized'] = supports
    if return_geometry:
        return result, stabilizers, generators, loops, winding, dict(
            faces=faces, path=path, vertices=vertices, embed=embed,
            shift=shift, conjugates=conjugates)
    return result


def loop_spectroscopy(L=4, couplings=(.2, .4, .5, .8, 1.0)):
    """Exact orbit of a selected Gamma-only perturbation; NOT full V41.

    H = g sum_p(1-Fp) - t sum_j Gj, g=1. Gj are the distinct-vertex
    perpendicular Gamma factors of the audited staircase winding string W.
    Product_j Gj = W and [Gj,W]=0. The straight Wx need not commute with
    the individual Gj outside the zero-flux code, so use W throughout.
    Pick a flux-free seed with W=s. Proper generator subsets have distinct
    syndromes modulo complementation; the orbit is exactly 2**(2L-1).
    No state or transition within this generated orbit is discarded.
    """
    from fractions import Fraction
    metadata, faces, generators, straight_loops, winding, geometry = audit(L, True)
    n = len(generators)
    full = (1 << n)-1
    dimension = 1 << (n-1)
    assert all(not anticommutes(a, b) for a, b in combinations(generators, 2))
    assert all(not anticommutes(winding, a) for a in faces + generators)
    columns = [sum(anticommutes(g, f) << k for k, f in enumerate(faces))
               for g in generators]
    syndromes = [0] * (1 << n)
    for mask in range(1, 1 << n):
        bit = mask & -mask
        syndromes[mask] = syndromes[mask ^ bit] ^ columns[bit.bit_length()-1]
    assert syndromes[full] == 0
    assert len(set(syndromes[:dimension])) == dimension
    assert all(syndromes[m] == syndromes[m ^ full] for m in range(1 << n))
    energies = [2 * syndrome.bit_count() for syndrome in syndromes]
    assert all(energies[m] > 0 for m in range(1, full))

    # Sum all n! ordered virtual winding paths, with exact rational denominators.
    # C has units g**(1-n), here g=1. The sector-odd term is -s*C*t**n.
    dp = [Fraction(0) for _ in range(1 << n)]
    dp[0] = Fraction(1)
    for mask in range(1, full):
        dp[mask] = sum((dp[mask ^ (1 << j)] for j in range(n)
                        if (mask >> j) & 1), Fraction(0)) / energies[mask]
    coefficient = sum((dp[full ^ (1 << j)] for j in range(n)), Fraction(0))
    index = np.arange(dimension)
    flips = [1 << j for j in range(n-1)] + [dimension-1]
    probe = np.eye(dimension)[index ^ flips[0]]

    def hamiltonian(s, t, cut=False):
        h = np.diag(np.array(energies[:dimension], dtype=float))
        for j, flip in enumerate(flips):
            if cut and j == n-1:
                continue
            h[index ^ flip, index] -= t * (s if j == n-1 else 1)
        assert np.array_equal(h, h.T)
        return h

    def response(h):
        evals, vecs = np.linalg.eigh(h)
        ground = vecs[:, 0]
        amplitudes = vecs.T @ (probe @ ground)
        weights = amplitudes**2
        assert abs(weights.sum() - 1) < 1e-12
        lines = []
        for delta, weight in zip(evals[1:]-evals[0], weights[1:]):
            if weight < 1e-12:
                continue
            if lines and abs(delta-lines[-1]['omega']) < 1e-8:
                lines[-1]['weight'] += float(weight)
            else:
                lines.append(dict(omega=float(delta), weight=float(weight)))
        return dict(ground_energy=float(evals[0]),
                    vacuum_overlap=float(ground[0]**2),
                    elastic_weight=float(weights[0]),
                    total_inelastic_weight=float(weights[1:].sum()),
                    first_moment=float(np.dot(evals-evals[0], weights)),
                    spectral_lines=lines,
                    strongest_line=max(lines, key=lambda line: line['weight']),
                    eigen_residual=float(np.linalg.norm(h @ vecs - vecs * evals)))

    runs = []
    for t in couplings:
        plus, minus = response(hamiltonian(1, t)), response(hamiltonian(-1, t))
        gap = minus['ground_energy'] - plus['ground_energy']
        predicted = 2 * float(coefficient) * t**n
        runs.append(dict(t_over_g=t, plus=plus, minus=minus,
                         ground_sector_splitting=gap,
                         leading_winding_prediction=predicted,
                         exact_over_leading=gap/predicted))
    # An open selected path cannot sense this winding sign: matrices coincide.
    cut_plus, cut_minus = hamiltonian(1, .5, True), hamiltonian(-1, .5, True)
    assert np.array_equal(cut_plus, cut_minus)
    return dict(scope='Selected Gamma-only perturbation, f=1; no rotor or slow m dynamics',
                L=L, generator_count=n, orbit_dimension_per_seed_and_sector=dimension,
                syndrome_rank=n-1,
                straight_Wx_flipped_by=sum(anticommutes(g, straight_loops[0])
                                          for g in generators),
                conserved_label='staircase W; equals straight Wx only on zero-flux code',
                local_probe='G0; conserves staircase W, can dephase superpositions of sectors',
                elementary_excitation_energies=sorted(set(energies[1 << j] for j in range(n))),
                winding_coefficient_exact=str(coefficient),
                winding_coefficient_float=float(coefficient),
                splitting_at_t_over_g_005_leading_only=2*float(coefficient)*.05**n,
                open_path_max_matrix_difference=float(np.max(abs(cut_plus-cut_minus))),
                runs=runs)


def native_rotor_winding_kernel(L=4, U=.2, M=4., Lambda=20., J=.05):
    """Lowest-order ORIGINAL Gamma*(T+Tdag) vacuum-to-loop matrix element.

    Here f=1, g=1, K=0; diagonal rotor electric, charge, and finite-Lambda
    terms are retained exactly. This is a controlled parameter slice, not
    the reference K=5 model or an invariant 0/1 rotor truncation.
    We compute the Feshbach effective kernel at spectral parameter E=0:
      <loop,s|H_eff(0)|vac,s> = -s C(0) J**(2L) + higher orders.
    Every shortest sequence applies each directed rotor shift exactly once.
    At this order no omitted link or repeated shift can reach the target.
    Gamma-only syndrome energies and actual rotor charges are both included.
    Final bare energy is L*U, not degenerate with vacuum; the matrix element
    is NOT an on-shell rate or a ground-sector splitting.
    """
    from fractions import Fraction
    _, faces, generators, _, winding, geo = audit(L, True)
    face_keys = list(geo['faces'])
    path = geo['path']
    n, full = len(path), (1 << len(path))-1
    def shifted(v, axis, amount=1):
        w = list(v)
        w[axis] = (w[axis]+amount) % L
        return tuple(w)
    edge_faces = {(v,a):0 for v in product(range(L), repeat=3) for a in range(3)}
    for k, (v, a, b) in enumerate(face_keys):
        for edge in [(v,a), (shifted(v,b),a), (v,b), (shifted(v,a),b)]:
            edge_faces[edge] |= 1 << k
    assert all(x.bit_count() == 4 for x in edge_faces.values())
    physical_path = [(shifted(v,d//2,-1) if d%2 else v, d//2) for v,d in path]
    assert len(set(physical_path)) == n
    columns = [sum(anticommutes(g, f) << k for k, f in enumerate(faces))
               for g in generators]
    syndrome = [0]*(1 << n)
    energy = [Fraction(0)]*(1 << n)
    components = []
    uq, mq, lq = map(lambda v:Fraction(str(v)), (U,M,Lambda))
    for mask in range(1 << n):
        if mask:
            bit = mask & -mask
            syndrome[mask] = syndrome[mask ^ bit] ^ columns[bit.bit_length()-1]
        b = [(mask >> j)&1 for j in range(n)]
        charges = {edge:b[j]-b[(j+1)%n] for j,edge in enumerate(physical_path)}
        charge_sq = sum(q*q for q in charges.values())
        mismatch = sum((charges.get(edge,0)**2-int(syndrome[mask]&fm == fm))**2
                       for edge,fm in edge_faces.items())
        gamma = 2*syndrome[mask].bit_count()
        energy[mask] = Fraction(gamma) + uq*mask.bit_count()/2 + mq*charge_sq/2 + lq*mismatch
        if mask in (0,1,3,full):
            components.append(dict(mask=mask,gamma_energy=gamma,
                                   electric_energy=float(uq*mask.bit_count()/2),
                                   charge_energy=float(mq*charge_sq/2),
                                   mismatch_energy=float(lq*mismatch),total=float(energy[mask])))
    assert energy[0] == 0 and energy[full] == uq*n/2
    assert all(energy[m] > energy[full] for m in range(1,full))
    dp = [Fraction(0)]*(1 << n)
    dp[0] = Fraction(1)
    for mask in range(1, full):
        dp[mask] = sum((dp[mask^(1<<j)] for j in range(n) if mask&(1<<j)),
                       Fraction(0))/energy[mask]
    coefficient = sum((dp[full^(1<<j)] for j in range(n)),Fraction(0))
    # Independent enumeration of all 8! paths checks signs/DP denominators.
    # Keep larger L out of the factorial check.
    if n <= 8:
        from itertools import permutations
        brute = 0.
        for order in permutations(range(n)):
            mask, term = 0, 1.
            for j in order[:-1]:
                mask |= 1<<j
                term /= float(energy[mask])
            brute += term
        assert abs(brute/float(coefficient)-1) < 1e-11
    return dict(scope='Original Gamma-rotor hopping, f=1, g=1, K=0 parameter slice',
                L=L, order=n, parameters=dict(U=U,M=M,Lambda=Lambda,J=J),
                kernel_spectral_parameter=0., final_bare_loop_energy=float(energy[full]),
                coefficient=float(coefficient), coefficient_exact=str(coefficient),
                matrix_element_magnitude_leading=float(coefficient)*J**n,
                intermediate_examples=components,
                meaning='Off-shell effective-kernel matrix element, not rate, gap, or physical frequency')


def compensated_symmetry_audit(L=4):
    """Exact algebraic symmetry of the V41 hopping INCLUDING its rotors.

    Let O be a Hermitian Pauli string commuting with every Fp. For every
    line-graph link ell=(v;a,b), set c_ell=1 if {O,Gamma_v^ab}=0, else 0.
    Define U_O = O exp(i*pi*sum_ell c_ell E_ell).
    E_ell is INTEGER, so U_O is a Hermitian involution. Conjugation changes
    both Gamma_ell and T_ell by (-1)**c_ell; their product is invariant.
    Electric, Q, F, nF, m, and p terms are invariant. Local rotor triangle
    products acquire no sign because Gamma_ab Gamma_bc Gamma_ca=-i I;
    elementary square products acquire none because their Gamma product
    is Fp and [O,Fp]=0. This covers the triangle/square K terms specified
    in V41, for arbitrary coefficients f(m), J, K, U, M, Lambda.

    This is an operator identity, not a rotor truncation or perturbation.
    It excludes additional noncontractible bare-rotor loops, boundaries,
    environments or probes not listed in that Hamiltonian.

    Three O=W_i give commuting symmetries; three O=D_i independently
    flip their signs. Hence every joint energy eigenstate has >=8 partners
    on these audited periodic lattices. D_i need not commute mutually.
    Any observable invariant under U_D has identical correlation functions
    in the corresponding symmetry-related states. Native Q,F,energy,
    and Gamma*(T-Tdag) currents are invariant. This obstructs readout
    through that observable family; it does not forbid every external probe.
    """
    _, faces, _, loops, _, geo = audit(L, True)
    embed, shift = geo['embed'], geo['shift']
    operators = loops + geo['conjugates']
    summaries = []
    for name, op in zip(['Wx','Wy','Wz','Dx','Dy','Dz'],operators):
        assert multiply(op,op) == (1,0,0)
        assert all(not anticommutes(op,f) for f in faces)
        signs = {(v,a,b):anticommutes(op,embed(v,a,b))
                 for v in geo['vertices'] for a,b in combinations(range(6),2)}
        def sign(v,a,b):
            return signs[v,min(a,b),max(a,b)]
        triangle_failures = 0
        for v in geo['vertices']:
            for a,b,c in combinations(range(6),3):
                triangle_failures += (sign(v,a,b)+sign(v,b,c)+sign(v,c,a))%2
        square_failures = 0
        for v,a,b in geo['faces']:
            va,vb=shift(v,a),shift(v,b)
            vab=shift(va,b)
            square_failures += (sign(v,2*b,2*a)+sign(va,2*a+1,2*b)
                                +sign(vab,2*b+1,2*a+1)+sign(vb,2*a,2*b+1))%2
        assert triangle_failures == square_failures == 0
        summaries.append(dict(logical_operator=name,
                              sign_compensated_links=sum(signs.values()),
                              triangle_sign_failures=triangle_failures,
                              square_sign_failures=square_failures))
    algebra = [[anticommutes(a,b) for b in operators] for a in operators]
    assert all(algebra[i][j] == 0 for i in range(3) for j in range(3))
    assert all(algebra[i][j+3] == int(i==j) for i in range(3) for j in range(3))
    return dict(L=L, operator_identity=True, tested_links_per_operator=15*L**3,
                tested_triangles_per_operator=20*L**3,
                tested_squares_per_operator=3*L**3,
                summaries=summaries, anticommutation_table=algebra,
                energy_multiplicity_lower_bound=8,
                readout_scope='Symmetry-related sectors, native invariant observables only',
                assumptions='Periodic audited lattice; K contains local triangles and elementary squares only')


def _native_layout(L):
    """Original link graph; canonical rotor orientation is port a -> b, a<b."""
    meta, stabilizers, _, straight, _, geo = audit(L, True)
    vertices, shift, embed = geo['vertices'], geo['shift'], geo['embed']
    edge_keys = [(v, a) for v in vertices for a in range(3)]
    edge_index = {edge: i for i, edge in enumerate(edge_keys)}
    links = [(v, a, b) for v in vertices for a, b in combinations(range(6), 2)]
    link_index = {ell: i for i, ell in enumerate(links)}

    def port_edge(v, a):
        return edge_index[(shift(v, a//2, -1) if a % 2 else v, a//2)]

    endpoints = [(port_edge(v, a), port_edge(v, b)) for v, a, b in links]
    # Twice the physical displacement of a canonical a->b link, using
    # the common original vertex as an unwrapped local coordinate chart.
    displacements2 = []
    for _, a, b in links:
        d = [0, 0, 0]
        d[a//2] -= (-1 if a % 2 else 1)
        d[b//2] += (-1 if b % 2 else 1)
        displacements2.append(tuple(d))
    face_boundaries, edge_faces = [], [0] * len(edge_keys)
    for k, (v, a, b) in enumerate(geo['faces']):
        boundary = [edge_index[e] for e in
                    [(v, a), (shift(v, b), a), (v, b), (shift(v, a), b)]]
        face_boundaries.append(set(boundary))
        for e in boundary:
            edge_faces[e] |= 1 << k
    assert all(mask.bit_count() == 4 for mask in edge_faces)
    gamma_syndromes = [sum(anticommutes(embed(v, a, b), f) << k
                           for k, f in enumerate(stabilizers)) for v, a, b in links]

    def directed(v, a, b):
        return link_index[(v, min(a, b), max(a, b))], 1 if a < b else -1

    triangles = [[directed(v, a, b), directed(v, b, c), directed(v, c, a)]
                 for v in vertices for a, b, c in combinations(range(6), 3)]
    squares = []
    for v, a, b in geo['faces']:
        va, vb = shift(v, a), shift(v, b)
        vab = shift(va, b)
        squares.append([directed(v, 2*b, 2*a), directed(va, 2*a+1, 2*b),
                        directed(vab, 2*b+1, 2*a+1), directed(vb, 2*a, 2*b+1)])
    return dict(L=L, metadata=meta, geo=geo, links=links, endpoints=endpoints,
                face_boundaries=face_boundaries, edge_faces=edge_faces,
                gamma_syndromes=gamma_syndromes, directed=directed,
                triangles=triangles, squares=squares, straight=straight,
                stabilizers=stabilizers, edge_keys=edge_keys,
                displacements2=displacements2)


def local_charge_flux_lock_audit(L=4):
    r"""Exact local conservation law, with all original K and J terms present.

    R_p = F_p exp(i*pi*sum_{e in boundary(p)} Q_e).
    A Gamma_ab hop anticommutes with F_p iff exactly one of the two
    physical edges belongs to boundary(p). The same hop flips that charge
    parity. Rotor K cycles preserve every Q and act trivially on Gamma.
    Hence [R_p,H]=0 for the COMPLETE listed V41 Hamiltonian, finite Lambda,
    arbitrary weights f(m), and arbitrary parameters, even time dependent
    coefficients of the same terms. No rotor cutoff or energy expansion.

    This is the previous compensated symmetry with O=F_p, now written
    entirely in terms of local physical observables. In the vacuum-connected
    sector R_p=+1, F_p=(-1)**sum_boundary_Q is an operator identity on
    that sector. In particular, definite Q_e=0 at EVERY edge forces F_p=+1.
    Merely <Q_e>=0 is not sufficient. This does not erase rotor correlations,
    phase information, global labels, or pre-existing slow m records.
    """
    lay = _native_layout(L)
    violations = 0
    for j, (ea, eb) in enumerate(lay['endpoints']):
        expected = sum(((ea in b) ^ (eb in b)) << k
                       for k, b in enumerate(lay['face_boundaries']))
        violations += (expected ^ lay['gamma_syndromes'][j]).bit_count()
    assert violations == 0
    # Check ALL K cycles using the original oriented incidence, not an
    # assumption that an arbitrary list of links happens to be a cycle.
    cycle_failures = winding_failures = 0
    for cycle in lay['triangles'] + lay['squares']:
        q = {}
        for j, direction in cycle:
            ea, eb = lay['endpoints'][j]
            q[ea] = q.get(ea, 0)-direction
            q[eb] = q.get(eb, 0)+direction
        cycle_failures += int(any(q.values()))
        net_displacement = [sum(direction*lay['displacements2'][j][a]
                                for j, direction in cycle) for a in range(3)]
        winding_failures += int(any(net_displacement))
    assert cycle_failures == winding_failures == 0
    return dict(L=L, operator_identity=True, face_link_pairs=
                len(lay['face_boundaries'])*len(lay['links']),
                gamma_charge_parity_mismatches=violations,
                local_K_cycles_checked=len(lay['triangles'])+len(lay['squares']),
                nonclosed_K_cycles=cycle_failures,
                K_cycles_changing_global_electric_winding=winding_failures,
                independent_local_invariants=lay['metadata']['stabilizer_rank'],
                formula='R_p = F_p * (-1)**sum_boundary(p)(Q_e); [R_p,H]=0',
                vacuum_sector='R_p=+1 => F_p=(-1)**sum_boundary(p)(Q_e)',
                consequence='No independently writable neutral local Gamma-flux record in this sector',
                qualification='Definite Q=0 everywhere, not zero mean charge; rotor/m/global records not excluded')


def native_memory_paths(L=4, U=.2, M=4., g=1., Lambda=20., J=.05, K=5.):
    """Full-network bare matrix elements and explicit paths, NOT lifetimes.

    All bare state energies are relative diagonal expectations at f=1.
    Every original term is retained when evaluating these matrix elements;
    K's common diagonal constant cancels. The bare states are not eigenstates
    at K=5 or J=.05. No claim of an invariant cropped Hilbert space is made.

    The straight noncontractible cycle is allowed because V41 includes all
    15 port pairs, including the 3 opposite pairs. The old staircase virtual
    process is one chosen target, not a lower bound on all winding processes.
    """
    from fractions import Fraction
    from itertools import permutations
    lay = _native_layout(L)
    n_edges = len(lay['edge_faces'])
    uq, mq, gq, lq = [Fraction(str(x)) for x in (U, M, g, Lambda)]

    def energy(E, syndrome):
        charges = [0] * n_edges
        for j, field in E.items():
            ea, eb = lay['endpoints'][j]
            charges[ea] -= field
            charges[eb] += field
        assert sum(charges) == 0
        parity_syndrome = sum((sum(charges[e] for e in b) % 2) << k
                              for k, b in enumerate(lay['face_boundaries']))
        assert syndrome == parity_syndrome
        q2 = sum(q*q for q in charges)
        nF = [int(syndrome & mask == mask) for mask in lay['edge_faces']]
        mismatch = sum((q*q-n)**2 for q, n in zip(charges, nF))
        pieces = dict(gamma=2*gq*syndrome.bit_count(),
                      electric=uq*sum(e*e for e in E.values())/2,
                      charge=mq*q2/2, mismatch=lq*mismatch)
        return sum(pieces.values()), dict(
            **{key: float(val) for key, val in pieces.items()},
            total=float(sum(pieces.values())),
            charged_edges=sum(q != 0 for q in charges),
            flipped_faces=syndrome.bit_count(), matched_indicators=sum(nF))

    def apply_path(hops, gamma_updates=True):
        E, syndrome = {}, 0
        rows = [dict(step=0, **energy(E, syndrome)[1])]
        for step, (j, direction) in enumerate(hops, 1):
            E[j] = E.get(j, 0)+direction
            if gamma_updates:
                syndrome ^= lay['gamma_syndromes'][j]
            rows.append(dict(step=step, **energy(E, syndrome)[1]))
        return E, syndrome, rows

    origin = (0, 0, 0)
    straight = [lay['directed']((x, 0, 0), 1, 0) for x in range(L)]
    loop_gamma = (1, 0, 0)
    for x in range(L):
        loop_gamma = multiply(loop_gamma, lay['geo']['embed']((x, 0, 0), 1, 0))
    assert loop_gamma == lay['straight'][0]  # L is even in this audit.
    _, final_syndrome, straight_rows = apply_path(straight)
    assert final_syndrome == 0
    for row in straight_rows[1:-1]:
        assert row['mismatch'] == 0 and row['charged_edges'] == 2
        assert abs(row['total']-(16*g+M+U*row['step']/2)) < 1e-12
    escape_height = max(row['total'] for row in straight_rows)-straight_rows[-1]['total']
    assert abs(escape_height-max(0., 16*g+M-U/2)) < 1e-12

    local_cycles = []
    for name, cycle in [('triangle', lay['triangles'][0]), ('square', lay['squares'][0])]:
        E, syndrome, rows = apply_path(cycle)
        assert syndrome == 0
        # A single ORIGINAL K term connects vacuum to this identical rotor
        # target, with unchanged Gamma. The J product is scalar on the
        # flux-free seed (triangle: phase; square: Fp=+1).
        target_energy = energy(E, 0)[1]
        local_cycles.append(dict(name=name, J_build_path=rows,
                                 K_direct_matrix_element=-K/2,
                                 bare_target_energy=target_energy['total'],
                                 erasure_diagonal_barrier_along_direct_K_edge=0.,
                                 matrix_element_over_bare_detuning=(K/2)/target_energy['total']))

    # All 2**L subsets of this straight cycle: exact diagonal energies.
    # The subset set is used ONLY to enumerate leading virtual paths, NOT
    # as a dynamically invariant 0/1 truncation.
    full = (1 << L)-1
    energies, energies_by_segments = [], []
    for mask in range(1 << L):
        E = {j:d for k, (j,d) in enumerate(straight) if (mask >> k)&1}
        syndrome = 0
        for k, (j, _) in enumerate(straight):
            if (mask >> k)&1:
                syndrome ^= lay['gamma_syndromes'][j]
        actual, _ = energy(E, syndrome)
        segments = sum(((mask >> k)&1) and not ((mask >> ((k-1)%L))&1) for k in range(L))
        predicted = (16*gq+mq)*segments+uq*mask.bit_count()/2
        assert actual == predicted
        energies.append(actual)
        energies_by_segments.append((segments, mask.bit_count()))
    dp = [Fraction(0)]*(1 << L)
    dp[0] = Fraction(1)
    for mask in range(1, full):
        dp[mask] = sum((dp[mask^(1 << j)] for j in range(L) if mask & (1 << j)),
                       Fraction(0))/energies[mask]
    coefficient = sum((dp[full^(1 << j)] for j in range(L)), Fraction(0))
    brute = 0.
    for order in permutations(range(L)):
        mask, term = 0, 1.
        for j in order[:-1]:
            mask |= 1 << j
            term /= float(energies[mask])
        brute += term
    assert abs(brute/float(coefficient)-1) < 1e-11

    first_steps = []
    for name, pair in [('perpendicular', (0, 2)), ('opposite', (0, 1))]:
        _, _, rows = apply_path([lay['directed'](origin, *pair)])
        first_steps.append(dict(port_pair=name, **rows[-1], hopping_magnitude=abs(J)))

    # A local readout diagnostic, separately from retention. At K=J=0,
    # each prepared bare state is an energy eigenstate. Use the SHAPE of
    # the original current as a weak probe, O=i Gamma_l(T_l-T_l^dag),
    # with unit probe coefficient. Its two transitions have unit weight.
    # We list signed Delta=E_final-E_initial (emission can be negative).
    # These are exact bare spectral lines, NOT the dressed K=5 spectrum.
    probe = lay['directed'](origin, 0, 2)[0]
    probe_spectra = []
    for length in (0, 1, 2):
        E, syndrome, _ = apply_path(straight[:length])
        initial, _ = energy(E, syndrome)
        transitions = []
        for direction in (-1, 1):
            target = dict(E)
            target[probe] = target.get(probe, 0)+direction
            final, _ = energy(target, syndrome ^ lay['gamma_syndromes'][probe])
            transitions.append(dict(delta_energy=float(final-initial), weight=1.))
        probe_spectra.append(dict(prepared_straight_segment_length=length,
                                  transitions=transitions))
    return dict(L=L, parameters=dict(U=U,M=M,g=g,Lambda=Lambda,J=J,K=K,f=1),
                first_steps=first_steps, local_cycles=local_cycles,
                straight_winding_build_path=straight_rows,
                reverse_path_barrier_upper_bound_bare=escape_height,
                straight_subset_energy_formula='(16*g+M)*number_of_occupied_segments + (U/2)*occupied_links',
                number_of_straight_subsets_checked=1 << L,
                bare_local_current_probe=dict(
                    scope='K=J=0 eigenstates; weak probe shape i*Gamma*(T-Tdag), unit coefficient',
                    probe_location='origin, ports +x,+y', runs=probe_spectra,
                    role='Distinguishability diagnostic only; no retention or full K=5 spectrum inferred'),
                straight_winding_kernel_K0=dict(
                    scope='K=0 ONLY, Feshbach kernel at E=0, selected straight-loop bare target',
                    order=L, coefficient_exact=str(coefficient), coefficient=float(coefficient),
                    leading_matrix_element_magnitude=float(coefficient)*J**L,
                    final_energy=float(energies[full]),
                    not_a_rate_gap_or_full_K5_prediction=True),
                conclusions=[
                    'Local rotor triangle/square flux has an original first-order K erasure channel.',
                    'Straight paths use allowed opposite ports and avoid Lambda mismatch entirely.',
                    'The explicit winding escape height is an upper bound on bare diagonal barriers only.',
                    'No glass phase, long-lived writable native memory, or physical lifetime is established.'])


def native_fermion_hopping_audit(L=4):
    """Exact Gamma*T hopping algebra, not a quasiparticle dispersion.

    At a line-graph site i (an original edge), ten hopping links split
    into two endpoint groups of five. Reversing three distinct factors
    gives one or three anticommutations. Independent rotor translations
    commute; they are kept as integer shift dictionaries, with no cutoff.
    Canonical Gamma_ab is used for BOTH directions, as in original H.
    The same multiset of commuting f(m_v) factors occurs on both sides.
    """
    lay = _native_layout(L)
    embed = lay['geo']['embed']
    adj = [[] for _ in lay['edge_keys']]
    for z, ((v, a, b), (ea, eb)) in enumerate(zip(lay['links'], lay['endpoints'])):
        op = embed(v, a, b)
        adj[ea].append((z, eb, v, op, -1))  # T exponent moving into ea
        adj[eb].append((z, ea, v, op, +1))
    counts = {1: 0, 3: 0}
    for neighbors in adj:
        assert len(neighbors) == 10
        assert len({x[1] for x in neighbors}) == 10
        for A, B, C in combinations(neighbors, 3):
            # h_il h_ki h_ij versus h_ij h_ki h_il; A,B,C = ij,ki,il.
            left = multiply(C[3], multiply(B[3], A[3]))
            right = multiply(A[3], multiply(B[3], C[3]))
            assert left[1:] == right[1:] and left[0] == -right[0]
            odd = sum(anticommutes(x[3], y[3])
                      for x, y in combinations((A, B, C), 2))
            assert odd in (1, 3)
            counts[odd] += 1
            directed_hops = [(A[0], A[4]), (B[0], -B[4]), (C[0], C[4])]
            shifts = []
            for hops in (directed_hops, directed_hops[::-1]):
                change = {}
                for z, direction in hops:
                    change[z] = change.get(z, 0) + direction
                shifts.append(change)
            assert shifts[0] == shifts[1]
    disjoint_local_checks = 0
    for v in lay['geo']['vertices']:
        for ab, cd in combinations(list(combinations(range(6), 2)), 2):
            if len(set(ab + cd)) == 4:
                assert not anticommutes(embed(v, *ab), embed(v, *cd))
                disjoint_local_checks += 1
    return dict(L=L, physical_charge_positions=len(adj), neighbors_per_position=10,
                exact_triple_checks=sum(counts.values()), failures=0,
                one_anticommutation=counts[1], three_anticommutations=counts[3],
                disjoint_local_hopping_checks=disjoint_local_checks,
                rotor_cutoff=None, exact_relative_sign=-1,
                applies_to='Original directed Gamma*T factors, also negative charges and arbitrary f(m)',
                not_computed=['Deconfined phase', 'Dressed spectral poles',
                              'Weyl dispersion', 'Lorentz spin', 'Gauge representations'])


def native_matched_exchange_audit(L=6, g=1., M=4.):
    """Two seven-hop products with a relative exchange and identical rotor output.

    All intermediate charge-flux configurations obey Q^2=nF. Four charges
    maintain total Q=0: two mobile +1 and two remote -1 spectators.
    This checks the statistics criterion within a nonempty matched support,
    not the full time evolution, deconfinement, or adiabatic exchange rate.
    """
    from collections import deque
    assert L >= 6 and L % 2 == 0
    lay = _native_layout(L)
    edge_index = {key: i for i, key in enumerate(lay['edge_keys'])}
    i = edge_index[((0, 0, 0), 0)]
    j = edge_index[((L-2, 0, 0), 0)]
    l = edge_index[((2, 0, 0), 0)]
    k = edge_index[((0, 2, 0), 1)]
    spectators = [edge_index[((1, 3, 3), 0)], edge_index[((4, 3, 3), 0)]]
    assert len({i, j, k, l, *spectators}) == 6
    directed = lay['directed']
    arm_j = [directed((L-1, 0, 0), 1, 0), directed((0, 0, 0), 1, 0)]
    arm_l = [directed((2, 0, 0), 0, 1), directed((1, 0, 0), 0, 1)]
    arm_k = [directed((0, 0, 0), 0, 2), directed((0, 1, 0), 3, 2),
             directed((0, 2, 0), 3, 2)]

    adj = [[] for _ in edge_index]
    for z, (ea, eb) in enumerate(lay['endpoints']):
        adj[ea].append((eb, z, +1))
        adj[eb].append((ea, z, -1))

    def shortest_path(source, destination):
        queue, predecessor = deque([source]), {source: None}
        while queue and destination not in predecessor:
            p = queue.popleft()
            for q, z, direction in adj[p]:
                if q not in predecessor:
                    predecessor[q] = (p, z, direction)
                    queue.append(q)
        assert destination in predecessor
        hops, q = [], destination
        while q != source:
            p, z, direction = predecessor[q]
            hops.append((z, direction))
            q = p
        return hops[::-1]

    def configuration(E, syndrome):
        q = [0] * len(edge_index)
        for z, field in E.items():
            a, b = lay['endpoints'][z]
            q[a] -= field
            q[b] += field
        parity = 0
        for e, value in enumerate(q):
            if value % 2:
                parity ^= lay['edge_faces'][e]
        assert parity == syndrome and sum(q) == 0
        nF = [int((syndrome & mask) == mask) for mask in lay['edge_faces']]
        mismatch = sum((value*value-n)**2 for value, n in zip(q, nF))
        row = dict(charged_edges=sum(x != 0 for x in q),
                   charge_square_sum=sum(x*x for x in q),
                   flipped_faces=syndrome.bit_count(), mismatch=mismatch,
                   gamma_plus_charge_energy=2*g*syndrome.bit_count()+M/2*sum(x*x for x in q))
        return q, row

    def update(E, syndrome, operator, hop):
        z, direction = hop
        E[z] = E.get(z, 0)+direction
        if E[z] == 0:
            del E[z]
        syndrome ^= lay['gamma_syndromes'][z]
        v, a, b = lay['links'][z]
        operator = multiply(lay['geo']['embed'](v, a, b), operator)
        return syndrome, operator

    # Explicit reachability from an allowed zero-charge, F=+1 vacuum.
    # Preparation may cross mismatch states; only the exchange paths below
    # are asserted to stay matched. Finite Lambda permits preparation.
    prepare = shortest_path(spectators[0], j)+shortest_path(spectators[1], l)
    initial_E, initial_syndrome, initial_operator = {}, 0, (1, 0, 0)
    for hop in prepare:
        initial_syndrome, initial_operator = update(
            initial_E, initial_syndrome, initial_operator, hop)
    q0, row0 = configuration(initial_E, initial_syndrome)
    assert {e: v for e, v in enumerate(q0) if v} == {
        j: 1, l: 1, spectators[0]: -1, spectators[1]: -1}
    assert row0['mismatch'] == 0

    def evolve(hops):
        E, syndrome, operator = dict(initial_E), initial_syndrome, (1, 0, 0)
        rows = [dict(step=0, **row0)]
        for step, hop in enumerate(hops, 1):
            syndrome, operator = update(E, syndrome, operator, hop)
            q, row = configuration(E, syndrome)
            assert row['mismatch'] == 0
            assert row['flipped_faces'] == 16 and row['charge_square_sum'] == 4
            rows.append(dict(step=step, **row))
        return E, syndrome, operator, q, rows

    A, B = evolve(arm_j+arm_k+arm_l), evolve(arm_l+arm_k+arm_j)
    assert A[0] == B[0] and A[1] == B[1] and A[3] == B[3]
    assert A[2][1:] == B[2][1:] and A[2][0] == -B[2][0]
    assert {e: v for e, v in enumerate(A[3]) if v} == {
        i: 1, k: 1, spectators[0]: -1, spectators[1]: -1}
    return dict(L=L, hops_per_sequence=7, preparation_hops=len(prepare),
                sequence_A='j->i; i->k; l->i', sequence_B='l->i; i->k; j->i',
                arm_lengths=[len(arm_j), len(arm_k), len(arm_l)],
                all_intermediates_matched=True, equal_final_Q_E_F=True,
                relative_Gamma_rotor_operator_sign=-1,
                path_A=A[4], path_B=B[4],
                scope='Ordered native hopping products; not full time-dependent amplitudes')


