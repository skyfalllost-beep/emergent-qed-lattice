def _expanded_laplace_kernel(delta,coeff):
    # vector-valued Horner evaluation in inverse gap
    inv=1/delta
    out=np.zeros_like(delta)
    for c in coeff[...,::-1].T:
        out=(out+c)*inv
    return out

def _expanded_patch_matrix(c,patch):
    from scipy.sparse import coo_matrix
    q0,G=c['q0'],c['G'];patch=np.array(sorted(patch));n=len(patch);k=int(sum(q0[patch]>0))
    codes=np.array(sorted(sum(1<<i for i in comb) for comb in combinations(range(n),k)),dtype=np.uint32)
    signs=2*((codes[:,None]>>np.arange(n))&1).astype(np.int8)-1
    dq=signs-q0[patch];phi0=G@q0;phi=dq@G[patch,:]+phi0
    energies=.1*(q0@G@q0+2*dq@phi0[patch]+np.einsum('bi,ij,bj->b',dq,G[np.ix_(patch,patch)],dq))
    shifts=np.empty(len(codes));minimum_gap=float('inf')
    aa,bb=c['aa'],c['bb'];coeff=c['returning'][c['kinds']]
    for start in range(0,len(codes),128):
        stop=min(start+128,len(codes));q=np.broadcast_to(q0,(stop-start,len(q0))).copy();q[:,patch]=signs[start:stop]
        sh=np.zeros(stop-start)
        for direction in (-1,1):
            x=q[:,aa]-direction;y=q[:,bb]+direction
            dc=c['fc']-6*(x*x+y*y-q[:,aa]**2-q[:,bb]**2)+20*(c['other']+(x*x-c['na'])**2+(y*y-c['nb'])**2)
            delta=dc+.2*direction*(phi[start:stop,bb]-phi[start:stop,aa])+c['selfc']
            minimum_gap=min(minimum_gap,float(np.min(delta)))
            sh-=_expanded_laplace_kernel(delta,coeff).sum(axis=1)
        shifts[start:stop]=sh
    mapping={e:i for i,e in enumerate(patch)};rows=[];cols=[];data=[]
    for ell,(x,y) in enumerate(c['endpoints']):
        if x not in mapping or y not in mapping:continue
        ix,iy=mapping[x],mapping[y];valid=np.where(signs[:,ix]==-signs[:,iy])[0]
        dest=np.searchsorted(codes,codes[valid]^((1<<ix)|(1<<iy)))
        mask=valid<dest;valid,dest=valid[mask],dest[mask]
        kind=c['kinds'][ell];core=136 if kind else 80
        di=core+.2*signs[valid,ix]*(phi[valid,y]-phi[valid,x])+c['selfc'][ell]
        df=core+.2*signs[dest,ix]*(phi[dest,y]-phi[dest,x])+c['selfc'][ell]
        tmag=(_laplace_from_derivatives(di,c['same'][kind])+_laplace_from_derivatives(df,c['same'][kind]))/2
        rows.extend([valid,dest]);cols.extend([dest,valid]);data.extend([-tmag,-tmag])
    off=coo_matrix((np.concatenate(data),(np.concatenate(rows),np.concatenate(cols))),shape=(len(codes),len(codes))).tocsr()
    refcode=sum(1<<i for i,x in enumerate(q0[patch]) if x>0);ref=int(np.searchsorted(codes,refcode))
    return dict(patch=patch,codes=codes,signs=signs,energies=energies,shifts=shifts,off=off,reference=ref,min_gap=minimum_gap)

def _expanded_patch_spectrum(context, patch, exchanges=(.05,.4,.6)):
    """Ground-state diagnostics for nested windows in one fixed L4 volume."""
    from scipy.sparse import diags
    from scipy.sparse.linalg import eigsh
    result=[]
    q_reference=context['q0'][patch['patch']]
    index={e:i for i,e in enumerate(patch['patch'])}
    center=[index[e] for e in context['hex']]
    assert len(center)==6
    for J in exchanges:
        diagonal=patch['energies']+J*J*patch['shifts']
        diagonal=diagonal-min(diagonal)
        H=diags(diagonal)+J*J*patch['off']
        initial=np.zeros(len(diagonal));initial[np.argmin(diagonal)]=1
        eigenvalue,eigenvector=eigsh(H,k=1,which='SA',v0=initial,tol=1e-11)
        psi=eigenvector[:,0];probability=abs(psi)**2
        residual=float(np.linalg.norm(H@psi-eigenvalue[0]*psi))
        assert residual<1e-10 and abs(sum(probability)-1)<1e-10
        if len(diagonal)==20:
            dense=np.linalg.eigh(H.toarray())
            assert abs(dense[0][0]-eigenvalue[0])<1e-12
            assert np.max(abs(dense[1][:,0]**2-probability))<1e-9
        mean=probability@patch['signs']
        result.append(dict(J=J,reference_configuration_probability=float(probability[patch['reference']]),
            mean_alignment=float(np.mean(mean*q_reference)),
            central_six_alignment=float(np.mean(mean[center]*q_reference[center])),
            effective_number_of_configurations=float(1/np.sum(probability**2)),
            lowering_below_smallest_diagonal=float(-eigenvalue[0]),eigenvector_residual=residual))
    return result


def _expanded_loop_paths(context,patch):
    """Compare effective exchange paths and a coherent finite-window evolution.

    A zero minimax barrier here refers ONLY to matched configuration energies.
    Every effective exchange still has the original costly virtual odd hop.
    No thermal rate or physical time calibration is inferred.
    """
    import heapq
    q0=context['q0'];positions=patch['patch'];codes=patch['codes'];E=patch['energies']
    H_off=patch['off'];returns=patch['shifts'];hexagon=context['hex']
    rows=[]
    for orientation in (1,-1):
        q=q0.copy();q[hexagon]=orientation*np.array([1,-1,1,-1,1,-1])
        code=sum(1<<i for i,e in enumerate(positions) if q[e]>0)
        start=int(np.searchsorted(codes,code));target=int(np.searchsorted(codes,code^63))
        assert abs(E[start]-E[target])<1e-12
        best=np.full(len(E),np.inf);best[start]=E[start];queue=[(E[start],start)];previous={}
        while queue:
            cost,i=heapq.heappop(queue)
            if cost>best[i]+1e-12:continue
            if i==target:break
            for j in H_off.getrow(i).indices:
                candidate=max(cost,E[j])
                if candidate<best[j]-1e-12:
                    best[j]=candidate;previous[j]=i;heapq.heappush(queue,(candidate,int(j)))
        path=[target]
        while path[-1]!=start:path.append(previous[path[-1]])
        path=path[::-1]
        neighbors=H_off.getrow(start).indices
        neighbor=int(neighbors[np.argmin(E[neighbors])])
        rows.append(dict(orientation=orientation,start=start,target=target,
            energy_above_static_minimum=float(E[start]-min(E)),
            matched_configuration_minimax_barrier=float(best[target]-E[start]),
            path=path,path_energies_relative_start=[float(E[i]-E[start]) for i in path],
            path_signs_in_hexagon_order=[patch['signs'][i,[list(positions).index(e) for e in hexagon]].tolist() for i in path],
            best_neighbor=neighbor,neighbor_static_difference=float(E[neighbor]-E[start]),
            neighbor_return_selfenergy_difference_at_J005=float(.05**2*(returns[neighbor]-returns[start])),
            neighbor_exchange_magnitude_at_J005=float(-.05**2*H_off[start,neighbor])))
    assert all(abs(row['matched_configuration_minimax_barrier'])<1e-12 for row in rows)
    # Retain the whole 20-state window, rather than replace it by two resonant states.
    J=.05;H=np.diag(E+J*J*returns)+J*J*H_off.toarray()
    values,vectors=np.linalg.eigh(H);initial=rows[0]['start'];neighbor=rows[0]['best_neighbor']
    magnitude=rows[0]['neighbor_exchange_magnitude_at_J005'];evolution=[]
    for scaled_time in (0.,np.pi/4,np.pi/2,np.pi):
        time=scaled_time/magnitude
        psi=vectors@(np.exp(-1j*(values-values[0])*time)*vectors[initial,:])
        norm=float(np.vdot(psi,psi).real);assert abs(norm-1)<1e-10
        evolution.append(dict(exchange_scaled_time=float(scaled_time),time_in_model_hbar_units=float(time),
            initial_configuration_probability=float(abs(psi[initial])**2),
            resonant_neighbor_probability=float(abs(psi[neighbor])**2),
            reverse_loop_probability=float(abs(psi[rows[0]['target']])**2),norm=norm))
    return dict(scope='Matched-source minimax paths and coherent 20-state effective dynamics, not thermal erasure',
                orientations=rows,coherent_evolution=evolution)


