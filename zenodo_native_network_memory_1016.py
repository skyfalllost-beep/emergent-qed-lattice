def _period_two_occupancy_geometry():
    """A period-two cell for infinite patterns, not a separate L=2 Gamma model."""
    vertices = list(product(range(2), repeat=3))
    edges = [(v, a) for v in vertices for a in range(3)]
    index = {edge: i for i, edge in enumerate(edges)}

    def shift(v, a):
        w = list(v); w[a] ^= 1
        return tuple(w)

    faces, masks = [], [0]*24
    for v in vertices:
        for a, b in combinations(range(3), 2):
            face = [index[v, a], index[shift(v, b), a],
                    index[v, b], index[shift(v, a), b]]
            p = len(faces)
            faces.append(face)
            for e in face:
                masks[e] |= 1 << p
    return vertices, edges, index, faces, masks, shift


def native_period_two_core_enumeration(batch_size=262144):
    """Exhaust ALL 2^24 period-two occupation patterns, integer arithmetic.

    F is fixed by charge parity in R=+1; nF is the AND of the four incident
    negative faces. Both matched and mismatched patterns are evaluated.
    This is a diagonal-core problem; rotor energy, J and quantum m excluded.
    At M=-12,-14.2 and Lambda=20, reducing |q| to 0 or 1 at fixed parity
    lowers the core (M >= -4 Lambda suffices). Thus no larger |q| can
    improve the corresponding unconstrained-sign core minimum.
    Actual neutral states for the winning pattern are constructed separately.
    """
    _, _, _, _, masks, _ = _period_two_occupancy_geometry()
    lookup = np.zeros((3, 256), dtype=np.uint32)
    pc = np.array([x.bit_count() for x in range(256)], dtype=np.int16)
    for block in range(3):
        for x in range(256):
            for b in range(8):
                if x & (1 << b):
                    lookup[block, x] ^= np.uint32(masks[8*block+b])

    def pop24(x):
        return pc[x & 255]+pc[(x >> 8) & 255]+pc[(x >> 16) & 255]

    from collections import Counter
    histogram = Counter()
    minima = {-120: dict(scaled_energy=10**9, degeneracy=0),
              -142: dict(scaled_energy=10**9, degeneracy=0)}
    for begin in range(0, 1 << 24, batch_size):
        x = np.arange(begin, min(begin+batch_size, 1 << 24), dtype=np.uint32)
        f = lookup[0, x & 255] ^ lookup[1, (x >> 8) & 255] ^ lookup[2, (x >> 16) & 255]
        nF = np.zeros_like(x)
        for e, mask in enumerate(masks):
            nF |= ((f & np.uint32(mask)) == mask).astype(np.uint32) << e
        n, nf, mismatch = pop24(x), pop24(f), pop24(x ^ nF)
        good = mismatch == 0
        keys, counts = np.unique((n[good]*25+nf[good]), return_counts=True)
        for key, count in zip(keys, counts):
            histogram[(int(key)//25, int(key)%25)] += int(count)
        # Multiply core energy by 20: 40 NF + (10 M) n + 400 mismatch.
        for m10, record in minima.items():
            energy20 = 40*nf.astype(np.int32)+m10*n.astype(np.int32)+400*mismatch.astype(np.int32)
            best = int(energy20.min())
            if best < record['scaled_energy']:
                record.update(scaled_energy=best, degeneracy=0)
            if best == record['scaled_energy']:
                record['degeneracy'] += int(np.sum(energy20 == best))
    expected = {(0,0):1, (1,4):24, (2,8):144, (3,12):64, (4,12):96, (6,16):24}
    assert dict(histogram) == expected
    assert minima[-120]['scaled_energy'] == -80
    assert minima[-142]['scaled_energy'] == -212
    assert all(r['degeneracy'] == 24 for r in minima.values())
    return dict(scope='Exact period-two diagonal-core search, NOT a global many-body ground-state solution',
                examined_patterns=1 << 24, matched_patterns=sum(histogram.values()),
                matched_histogram=[dict(occupied_edges=n, negative_faces=f, count=c)
                                   for (n,f),c in sorted(histogram.items())],
                finite_Lambda_minima=[dict(M=m10/10, Lambda=20,
                    energy_per_eight_vertex_cell=r['scaled_energy']/20,
                    occupation_pattern_degeneracy=r['degeneracy']) for m10,r in minima.items()],
                matched_core_onset_M=-32/3,
                larger_period_optimality_proved=False)


def native_layered_background(L=4, U=.2, g=1., M=-12., Lambda=20., J=.05):
    """Explicit neutral layered trial state and exact local hopping selection.

    Static variational comparison: f=1,J=0, arbitrary K, compact rotors retained.
    Local core costs exclude rotor reorganization and quantum m. Two-hop tests
    count operator-allowed charge changes; they do not replace the full
    intermediate-state resolvent by a single classical energy denominator.
    """
    assert L >= 4 and L % 2 == 0
    from collections import Counter, deque
    lay = _native_layout(L)
    V, ne = L**3, len(lay['edge_keys'])
    flow, syndrome = {}, 0
    for x, y, z in product(range(0, L, 2), repeat=3):
        operations = [((x, y+1, z+1), 3, 2),
                      ((x+1, y, z+1), 1, 2),
                      ((x+1, y+1, z+1), 0, 2)]
        for v, a, b in operations:
            ell, direction = lay['directed'](v, a, b)
            assert ell not in flow
            flow[ell] = direction
            syndrome ^= lay['gamma_syndromes'][ell]
    q = np.zeros(ne, dtype=int)
    for ell, d in flow.items():
        a, b = lay['endpoints'][ell]
        q[a] -= d; q[b] += d
    masks = lay['edge_faces']
    nF = np.array([int(syndrome & mask == mask) for mask in masks])
    formula = np.array([int(v[2] % 2 == 1 and
                    (a == 1 or (a == 0 and (v[0]+v[1]) % 2 == 0)))
                    for v, a in lay['edge_keys']])
    assert sum(q) == 0 and np.array_equal(q*q, nF) and np.array_equal(nF, formula)
    occupied = int(q @ q); nf = syndrome.bit_count(); norm2 = sum(d*d for d in flow.values())
    assert occupied == 3*V//4 and nf == 2*V and norm2 == 3*V//8
    trial_density = (2*g*nf+M*occupied/2+U*norm2/2)/V
    assert abs(trial_density-(4*g+3*M/8+3*U/16)) < 1e-12

    def core(qq, ss):
        mismatch = sum((int(qq[e])**2-int(ss & mask == mask))**2
                       for e, mask in enumerate(masks))
        return 2*g*ss.bit_count()+M*int(qq @ qq)/2+Lambda*mismatch

    oldcore = core(q, syndrome)
    single_core = Counter(); single_matched = 0; trial_costs = []
    first_parity = []
    xmask = sum(1 << e for e in range(ne) if nF[e])
    for ell, (a, b) in enumerate(lay['endpoints']):
        first_parity.append((1 << a) | (1 << b))
        for d in (-1, 1):
            qq = q.copy(); qq[a] -= d; qq[b] += d
            ss = syndrome ^ lay['gamma_syndromes'][ell]
            dc = float(core(qq, ss)-oldcore)
            single_core[round(dc, 10)] += 1
            trial_costs.append(dc+U*(1+2*flow.get(ell, 0)*d)/2)
            single_matched += int(all(int(qq[e])**2 == int(ss & mask == mask)
                                      for e, mask in enumerate(masks)))
    assert single_matched == 0

    # Period-two translation symmetry reduces the first link to 120 representatives.
    representatives = [i for i, (v,a,b) in enumerate(lay['links']) if all(t < 2 for t in v)]
    matched_distinct_pairs = 0
    for i in representatives:
        for j in range(len(first_parity)):
            if i == j:
                continue
            xx = xmask ^ first_parity[i] ^ first_parity[j]
            ss = syndrome ^ lay['gamma_syndromes'][i] ^ lay['gamma_syndromes'][j]
            if all(bool(xx & (1 << e)) == (ss & mask == mask) for e,mask in enumerate(masks)):
                matched_distinct_pairs += 1
    assert matched_distinct_pairs == 0

    # Two identical directed hops exchange -1,+1, leaving occupation and F fixed.
    graph = {e: [] for e in range(ne) if nF[e]}
    exchange_core = Counter(); occupied_bonds = 0
    for ell, (a, b) in enumerate(lay['endpoints']):
        if a not in graph or b not in graph:
            continue
        occupied_bonds += 1
        graph[a].append(b); graph[b].append(a)
        if q[a] != -q[b]:
            continue
        d = int(q[a]); mid = q.copy(); mid[a] -= d; mid[b] += d
        end = mid.copy(); end[a] -= d; end[b] += d
        assert end[a] == q[b] and end[b] == q[a] and np.array_equal(end*end, nF)
        exchange_core[round(float(core(mid, syndrome ^ lay['gamma_syndromes'][ell])-oldcore),10)] += 1
    seen, components = set(), []
    for e in graph:
        if e in seen:
            continue
        todo = [e]; seen.add(e); component = []
        while todo:
            a = todo.pop(); component.append(a)
            for b in graph[a]:
                if b not in seen:
                    seen.add(b); todo.append(b)
        z_values = {lay['edge_keys'][i][0][2] for i in component}
        assert len(z_values) == 1
        components.append(dict(z=next(iter(z_values)), sites=len(component)))
    assert len(components) == L//2 and all(len(ns) == 4 for ns in graph.values())
    # Minimum full line-graph distance between distinct occupied layers.
    all_adj = [[] for _ in range(ne)]
    for a,b in lay['endpoints']:
        all_adj[a].append(b); all_adj[b].append(a)
    sources = [e for e in graph if lay['edge_keys'][e][0][2] == 1]
    dist = {e:0 for e in sources}; todo = deque(sources)
    while todo:
        a = todo.popleft()
        for b in all_adj[a]:
            if b not in dist:
                dist[b] = dist[a]+1; todo.append(b)
    separation = min(dist[e] for e in graph if lay['edge_keys'][e][0][2] != 1)
    assert separation == 3
    return dict(L=L, scope='Explicit layered variational state; static bound at f=1,J=0; local operator checks',
                occupied_edges=occupied, negative_faces=nf, mismatch=0,
                integer_flow_norm_squared=norm2,
                trial_energy_density_relative_neutral=trial_density,
                sufficient_neutral_instability_M=-32*g/3-U/2,
                actual_global_ground_state_proved=False,
                single_directed_hops_checked=2*len(lay['links']),
                matched_single_hops=single_matched,
                minimum_single_hop_core_cost=min(single_core),
                minimum_single_hop_trial_expectation_cost=min(trial_costs),
                core_costs_are_not_full_rotor_spectral_gaps=True,
                distinct_two_hop_first_link_representatives=len(representatives),
                matched_distinct_two_link_parities=matched_distinct_pairs,
                same_link_charge_exchange_intermediate_core_costs=[dict(cost=c,count=n)
                    for c,n in sorted(exchange_core.items())],
                core_denominator_estimates_only=[dict(core_denominator=c,J_squared_over_core=J*J/c)
                    for c in sorted(exchange_core)],
                exchange_graph='Line graph of brick-wall honeycomb layers: anisotropic kagome connectivity',
                occupied_neighbor_bonds=occupied_bonds, degree=4, components=components,
                adjacent_layer_line_graph_distance=separation,
                fixed_occupation_interlayer_charge_transfer_minimum_hop_order=2*separation,
                full_effective_exchange_amplitude_computed=False,
                Weyl_spectrum_computed=False)


def native_layered_sign_electrostatics(U=.2):
    """All 20 neutral sign assignments in one fixed six-occupied-edge cell.

    Coulomb lower bound for compact J=0 rotors; equality only in the
    noncompact Gaussian approximation. A period-two sign restriction is
    imposed; this does NOT minimize over larger sign cells or quantum states.
    """
    vertices, edges, index, _, _, _ = _period_two_occupancy_geometry()
    endpoints = []
    for v in vertices:
        ports = []
        for a in range(6):
            w = list(v)
            if a % 2:
                w[a//2] ^= 1
            ports.append(index[tuple(w), a//2])
        endpoints.extend(combinations(ports, 2))
    B = np.zeros((24, len(endpoints)))
    for ell, (a,b) in enumerate(endpoints):
        B[a,ell] = -1; B[b,ell] = 1
    G = np.linalg.pinv(B @ B.T, hermitian=True)
    occupied = [e for e,(v,a) in enumerate(edges) if v[2]%2 == 1 and
                (a == 1 or (a == 0 and (v[0]+v[1])%2 == 0))]
    from collections import Counter
    energies = Counter()
    for positive in combinations(occupied, 3):
        q = np.zeros(24); q[occupied] = -1; q[list(positive)] = 1
        energies[round(float(U*q @ G @ q/2), 12)] += 1
    assert sum(energies.values()) == 20
    if U == .2:
        assert dict(energies) == {.05625:16, .08125:4}
    return dict(scope='Period-two fixed occupation, static Coulomb kernel; Gaussian equality only',
                neutral_sign_patterns=20,
                energies_per_eight_vertex_cell=[dict(energy=e,count=n) for e,n in sorted(energies.items())],
                sign_ground_state_for_full_model_solved=False)


def _rectangular_coulomb_geometry(shape):
    """Periodic SOURCE cell, obtained by folding the original infinite graph."""
    assert all(s >= 2 and s % 2 == 0 for s in shape)
    vertices = list(product(*(range(s) for s in shape)))
    edges = [(v, a) for v in vertices for a in range(3)]
    vi = {v: i for i, v in enumerate(vertices)}
    incidence = np.zeros((len(vertices), len(edges)))
    for e, (v, a) in enumerate(edges):
        w = list(v); w[a] = (w[a]+1) % shape[a]
        incidence[vi[v], e] += 1
        incidence[vi[tuple(w)], e] += 1
    G = np.linalg.pinv(12*np.eye(len(edges))-incidence.T @ incidence, hermitian=True)
    occupied = [i for i,(v,a) in enumerate(edges) if v[2]%2 == 1 and
                (a == 1 or (a == 0 and (v[0]+v[1])%2 == 0))]
    return vertices, edges, incidence, G, occupied


def native_extended_sign_search(U=.2, return_seed=False):
    """Exact enumeration within EACH specified classical periodic sign ansatz.

    The 20 period-two sign patterns are NOT used as 20 local quantum basis
    states: changing a periodic pattern would change every repeated cell.
    All energies here are Coulomb-kernel values, Gaussian static equalities.
    The kernel remains only a lower bound for compact-rotor sector energies.
    """
    from math import comb
    pc = np.array([i.bit_count() for i in range(256)], dtype=np.int16)
    rows, seed = [], None
    for shape in ((2,2,2), (2,2,4), (4,2,2), (4,4,2), (4,2,4)):
        vertices, edges, C, G, occupied = _rectangular_coulomb_geometry(shape)
        n = len(occupied); matrix = U*G[np.ix_(occupied, occupied)]/2
        best, second, count, tested, example = float('inf'), float('inf'), 0, 0, None
        for begin in range(0, 1 << n, 65536):
            x = np.arange(begin, min(begin+65536, 1 << n), dtype=np.uint32)
            number = pc[x & 255]+pc[(x >> 8) & 255]+pc[(x >> 16) & 255]
            x = x[number == n//2]; tested += len(x)
            if not len(x):
                continue
            qs = 2*((x[:,None] >> np.arange(n, dtype=np.uint32)) & 1).astype(float)-1
            energies = np.round(np.einsum('bi,ij,bj->b', qs, matrix, qs, optimize=True), 12)
            current = float(energies.min())
            if current < best-1e-10:
                second, best, count = best, current, 0
                example = qs[np.argmin(energies)].astype(int)
            if abs(current-best) < 1e-10:
                count += int(np.sum(abs(energies-best) < 1e-10))
            bigger = energies[energies > best+1e-10]
            if len(bigger):
                second = min(second, float(bigger.min()))
        assert tested == comb(n, n//2)
        q = np.zeros(len(edges)); q[occupied] = example
        rho = C @ q
        assert np.max(abs(rho)) == 1
        row = dict(shape=shape, sign_sites=n, neutral_sign_patterns=tested,
                   coulomb_minimum_per_cell=best, energy_density=best/len(vertices),
                   number_of_minimizing_sign_patterns=count,
                   next_distinct_classical_energy_gap=second-best)
        rows.append(row)
        if shape == (4,4,2):
            seed = {edges[i]: int(v) for i,v in zip(occupied, example)}
    result = dict(scope='Exhaustive classical sign search in five specified periodic cells, fixed layered occupation',
                  rows=rows, global_optimization_proved=False)
    return (result, seed) if return_seed else result


def _native_transverse_mode_weights(N, U=.2, K=5.):
    """Full positive-mode spectrum for a representative turn and straight link."""
    pairs = list(combinations(range(6), 2))
    selected = [pairs.index((0,2)), pairs.index((0,1))]
    frequencies, weights = [], []
    k = 2*np.pi*np.arange(N)/N
    xy = np.array(np.meshgrid(k, k, indexing='ij')).reshape(2, -1).T
    for kz in k:
        ks = np.column_stack((xy, np.full(len(xy), kz)))
        _, C = _native_rotor_bloch(ks)
        eig, vec = np.linalg.eigh(C.conj().swapaxes(1,2) @ C)
        roots = np.sqrt(np.maximum(eig, 0))
        inv = np.divide(1, roots, out=np.zeros_like(roots), where=eig > 1e-9)
        weight = .5*np.sqrt(U/K)*abs(vec[:,selected,:])**2*inv[:,None,:]/N**3
        frequencies.append((np.sqrt(U*K)*roots).reshape(-1))
        weights.append(weight.transpose(1,0,2).reshape(2,-1))
    return np.concatenate(frequencies), np.concatenate(weights, axis=1)


def _laplace_kernel_derivatives(frequencies, weights, exchange, order=8):
    """Derivatives at tau=0 of exp[-S +/- C(tau)], using Bell recurrence."""
    from math import comb
    moments = [float(weights @ frequencies**n) for n in range(order+1)]
    derivatives = np.ones(order+1)
    for n in range(1, order+1):
        derivatives[n] = sum(comb(n-1,k-1)*(1 if exchange else -1)*(-1)**(k+1)
                             *moments[k]*derivatives[n-k] for k in range(1,n+1))
    if exchange:
        derivatives *= np.exp(-2*moments[0])
    return derivatives


def _laplace_from_derivatives(delta, derivatives):
    delta = np.asarray(delta)
    return sum(coefficient/delta**(n+1) for n,coefficient in enumerate(derivatives))


def _gaussian_resolvent_fock_check():
    """Independent two-oscillator matrix check of same/return displacement signs."""
    size = 12
    annihilate = np.diag(np.sqrt(np.arange(1,size)), 1)
    omega, variances, displacements = [.7, 2.3], [.015, .025], []
    for variance in variances:
        values, vectors = np.linalg.eigh(np.sqrt(variance)*(annihilate+annihilate.T))
        displacements.append((vectors*np.exp(1j*values)) @ vectors.T)
    W = np.kron(*displacements)
    energies = np.array([omega[0]*i+omega[1]*j for i,j in product(range(size),repeat=2)])
    nodes, quadrature_weights = np.polynomial.laguerre.laggauss(32)
    correlation = np.exp(-nodes[:,None]*np.asarray(omega)/80) @ variances
    errors = []
    for exchange, right in ((True, W), (False, W.conj().T)):
        direct = np.sum(W[0,:]*right[:,0]/(80+energies))
        integral = quadrature_weights @ np.exp(-sum(variances)+( -1 if exchange else 1)*correlation)/80
        errors.append(float(abs(direct-integral)))
    assert max(errors) < 1e-12
    return dict(oscillator_cutoff=size, dimension=size**2,
                same_displacement_error=errors[0], return_displacement_error=errors[1])


def native_gaussian_exchange_resolvent(mesh_sizes=(8,16,24), U=.2, K=5., J=.05,
                                      return_kernels=False):
    """Two-hop matrix elements with all virtual Gaussian transverse oscillators.

    f=1, noncompact quadratic rotor background; zero transverse-photon external
    states. Global harmonic/holonomy modes and compact nonperturbative effects
    are not computed. This is not the full compact-model exchange amplitude.
    """
    rows, final_same, final_return, maximum_error = [], None, None, 0.
    for N in mesh_sizes:
        frequencies, weights = _native_transverse_mode_weights(N, U, K)
        same, returning, links = [], [], []
        for name, weight, delta in zip(('turn','straight'), weights, (80.,136.)):
            d_same = _laplace_kernel_derivatives(frequencies, weight, True)
            d_return = _laplace_kernel_derivatives(frequencies, weight, False)
            same.append(d_same); returning.append(d_return)
            nodes, qweights = np.polynomial.laguerre.laggauss(32)
            correlation = np.exp(-nodes[:,None]*frequencies[None,:]/delta) @ weight
            exact = float(qweights @ np.exp(-weight.sum()-correlation)/delta)
            error = float(abs(_laplace_from_derivatives(delta,d_same)/exact-1))
            maximum_error = max(maximum_error, error)
            if N == mesh_sizes[-1]:
                # Check the fast derivative evaluation over the complete patch gap range.
                for gap in (75.,300.,750.):
                    corr = np.exp(-nodes[:,None]*frequencies[None,:]/gap) @ weight
                    for exchange, ds in ((True,d_same),(False,d_return)):
                        val = float(qweights @ np.exp(-weight.sum()+(-1 if exchange else 1)*corr)/gap)
                        maximum_error = max(maximum_error, float(abs(_laplace_from_derivatives(gap,ds)/val-1)))
            links.append(dict(kind=name, core_gap=delta, transverse_variance=float(weight.sum()),
                              exchange_magnitude=J*J*exact,
                              ratio_to_J_squared_over_core=exact*delta,
                              integral_derivative_relative_difference=error))
        final_same, final_return = same, returning
        rows.append(dict(momentum_mesh=N, links=links))
    assert maximum_error < 1e-9
    result = dict(scope='Gaussian transverse vacuum matrix elements, two-hop order; full compact amplitude not solved',
                  rows=rows, maximum_fast_integral_check_relative_error=maximum_error,
                  independent_fock_check=_gaussian_resolvent_fock_check(),
                  kernel_exchange='exp[-S-C(tau)]', kernel_return='exp[-S+C(tau)]')
    return (result, final_same, final_return) if return_kernels else result


def native_layered_quantum_patch():
    """P*h_eff^(2)*P for six ACTUAL occupied positions, others pinned, L=4.

    Two successive approximations: noncompact Gaussian transverse-vacuum
    matrix elements, then a physical six-position subspace with fixed exterior
    charges. All original one-hop return paths enter the diagonal self energy.
    This is NOT a quantum superposition of periodic ansatz labels, and neither
    its probability nor its gap is a thermodynamic phase or a lifetime.
    """
    search, seed = native_extended_sign_search(return_seed=True)
    # Use the same L=4 volume for source electrostatics and transverse modes.
    # Larger meshes below are a separate convergence diagnostic, not a bulk
    # kernel silently substituted into the finite-patch Hamiltonian.
    resolvent = native_gaussian_exchange_resolvent(mesh_sizes=(4,8,16,24))
    U, g, M, Lambda, J0, L = .2, 1., -12., 20., .05, 4
    frequencies, weights = _native_transverse_mode_weights(L, U, 5.)
    same = [_laplace_kernel_derivatives(frequencies, w, True) for w in weights]
    returning = [_laplace_kernel_derivatives(frequencies, w, False) for w in weights]
    lay = _native_layout(L)
    q0 = np.array([seed.get(((v[0],v[1],1),a),0)*(-1)**((v[2]-1)//2)
                   if v[2]%2 else 0 for v,a in lay['edge_keys']])
    endpoints = np.asarray(lay['endpoints']); aa,bb = endpoints.T
    B = np.zeros((len(q0),len(endpoints)))
    for ell,(a,b) in enumerate(endpoints):
        B[a,ell],B[b,ell] = -1,1
    G = np.linalg.pinv(B @ B.T, hermitian=True)
    _,_,C,_,_ = _rectangular_coulomb_geometry((4,4,4))
    rho = C @ q0
    original_lap = 12*np.eye(L**3)-C @ C.T
    G_vertex = np.linalg.pinv(original_lap, hermitian=True)
    ec_reference = float(U*q0 @ G @ q0/2)
    decomposition = float(U*(q0 @ q0+rho @ G_vertex @ rho)/24)
    assert abs(ec_reference-decomposition) < 1e-12
    assert abs(ec_reference/L**3-.006770833333333333) < 1e-12
    assert np.max(abs(rho)) == 1 and sum(q0) == 0
    syndrome = 0
    for e,q in enumerate(q0):
        if q:
            syndrome ^= lay['edge_faces'][e]
    occupation = q0*q0
    assert all(occupation[e] == int(syndrome & m == m) for e,m in enumerate(lay['edge_faces']))
    kinds = np.array([int(a//2 == b//2) for v,a,b in lay['links']])
    face_cost, n_a, n_b, other_mismatch = [], [], [], []
    for ell,(a,b) in enumerate(endpoints):
        s = syndrome ^ lay['gamma_syndromes'][ell]
        n = np.array([int(s & mask == mask) for mask in lay['edge_faces']])
        face_cost.append(2*g*(s.bit_count()-syndrome.bit_count()))
        n_a.append(n[a]); n_b.append(n[b])
        other_mismatch.append(int(sum((occupation-n)**2)-(occupation[a]-n[a])**2-(occupation[b]-n[b])**2))
    face_cost,n_a,n_b,other_mismatch = map(np.asarray,(face_cost,n_a,n_b,other_mismatch))
    electric_self_shift = U*(G[aa,aa]+G[bb,bb]-2*G[aa,bb])/2

    def gaps(q,direction):
        a,b = q[aa]-direction,q[bb]+direction
        dc = face_cost+M*(a*a+b*b-q[aa]**2-q[bb]**2)/2
        dc += Lambda*(other_mismatch+(a*a-n_a)**2+(b*b-n_b)**2)
        phi = G @ q
        return dc+U*direction*(phi[bb]-phi[aa])+electric_self_shift

    index = {edge:i for i,edge in enumerate(lay['edge_keys'])}
    patch = np.array([index[e] for e in [((0,0,1),0),((1,0,1),1),((1,1,1),1),
                                        ((0,2,1),0),((0,1,1),1),((0,0,1),1)]])
    assert sum(q0[patch]) == 0
