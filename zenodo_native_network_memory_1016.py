def _native_rotor_bloch(ks):
    """B: divergence (3x15); C: original loop curls (23x15), per momentum.

    Link cells are the original vertex; negative ports touch an original
    edge whose tail lies one unit behind it. These cell offsets MUST be
    retained. All 20 port triangles and all 3 original squares are used.
    """
    ks = np.asarray(ks, float).reshape(-1, 3)
    pairs = list(combinations(range(6), 2))
    index = {pair: i for i, pair in enumerate(pairs)}
    B = np.zeros((len(ks), 3, 15), complex)
    C = np.zeros((len(ks), 23, 15), complex)
    for z, (a, b) in enumerate(pairs):
        B[:, a//2, z] -= np.exp(1j*ks[:, a//2]*(a % 2))
        B[:, b//2, z] += np.exp(1j*ks[:, b//2]*(b % 2))

    def add(row, a, b, offset):
        z = index[tuple(sorted((a, b)))]
        direction = 1 if a < b else -1
        C[:, row, z] += direction*np.exp(1j*(ks @ np.asarray(offset)))

    for row, (a, b, c) in enumerate(combinations(range(6), 3)):
        for aa, bb in ((a, b), (b, c), (c, a)):
            add(row, aa, bb, (0, 0, 0))
    for row, (a, b) in enumerate(combinations(range(3), 2), 20):
        ea, eb = np.eye(3, dtype=int)[a], np.eye(3, dtype=int)[b]
        for aa, bb, offset in ((2*b, 2*a, (0, 0, 0)), (2*a+1, 2*b, ea),
                              (2*b+1, 2*a+1, ea+eb), (2*a, 2*b+1, eb)):
            add(row, aa, bb, offset)
    return B, C


def native_electrostatic_audit(mesh_sizes=(16, 32, 64, 128), U=.2):
    """Compact static-sector LOWER bound; equality in noncompact Gaussian theory.

    E_C(q)=U/2 q^T (B B^T)^+ q. Matrix inverse formula is analytic;
    Fourier transforms only evaluate the lattice Green function. The
    three positive original edge directions are the unit-cell orbitals.
    """
    assert U > 0

    def green(N):
        k = 2*np.pi*np.arange(N)/N
        d = 2*(1-np.cos(k))
        lap = d[:, None, None]+d[None, :, None]+d[None, None, :]
        inv = np.divide(1, lap, out=np.zeros_like(lap), where=lap > 1e-12)
        Gk = 1/12+(2+2*np.cos(k[:, None, None]))*inv/12
        Gk[0, 0, 0] = 1/18  # diagonal of (I-P_uniform)/12 at k=0
        return np.fft.ifftn(Gk).real

    # Independent real-space incidence solve, not a Fourier identity test.
    lay = _native_layout(4)
    B = np.zeros((len(lay['edge_keys']), len(lay['links'])))
    for z, (a, b) in enumerate(lay['endpoints']):
        B[a, z], B[b, z] = -1, +1
    lap = B @ B.T
    G = np.linalg.pinv(lap, hermitian=True)
    q = np.zeros(len(lap))
    ei = {key: i for i, key in enumerate(lay['edge_keys'])}
    q[ei[((0, 0, 0), 0)]], q[ei[((1, 0, 0), 0)]] = +1, -1
    field = B.T @ G @ q
    residual = float(np.max(abs(B @ field-q)))
    direct = float(U/2*np.dot(field, field))
    Gfft = green(4)
    fourier = float(U*(Gfft[0, 0, 0]-Gfft[1, 0, 0]))
    assert residual < 1e-12 and abs(direct-fourier) < 1e-12
    assert np.max(np.linalg.eigvalsh(lap)) <= 12+1e-10

    rows = []
    for N in mesh_sizes:
        Gfft = green(N)
        distances = []
        for r in (1, 2, 4, 8, 12, 16, 24):
            if r >= N//2:
                continue
            energy = float(U*(Gfft[0, 0, 0]-Gfft[r, 0, 0]))
            slope = float(U*(Gfft[r, 0, 0]-Gfft[r+1, 0, 0]))
            continuum_slope = U/(12*np.pi)*(1/r-1/(r+1))
            distances.append(dict(r=r, coulomb_lower_bound=energy,
                                  integer_straight_path_upper_bound=U*r/2,
                                  gaussian_energy_increment=slope,
                                  asymptotic_energy_increment=continuum_slope,
                                  increment_ratio=slope/continuum_slope))
        rows.append(dict(L=N, finite_volume_diagonal_self_pair=U*float(Gfft[0, 0, 0]),
                         distances=distances))
    extrapolation = None
    if len(rows) >= 3:
        last = rows[-3:]
        fit = np.array([[1, 1/r['L'], 1/r['L']**3] for r in last])
        coefficients = np.linalg.solve(fit, [r['finite_volume_diagonal_self_pair'] for r in last])
        extrapolation = dict(infinite_volume_self_pair=float(coefficients[0]),
                             method='Three-point fit a+b/L+c/L^3; numerical estimate, not a rigorous bound')
    return dict(scope='Frozen f=1, J=0; E_C is exact compact lower bound and noncompact Gaussian energy',
                real_space_check=dict(L=4, divergence_residual=residual,
                                      direct_energy=direct, fourier_energy=fourier),
                asymptotic_interaction_coefficient=-U/(12*np.pi),
                compact_deconfinement_proved=False, rows=rows, extrapolation=extrapolation)


def native_gaussian_rotor_dressing(mesh_sizes=(8, 16, 24, 32), U=.2, K=5., J=.05):
    """Original geometry, frozen f=1, noncompact Gaussian background ONLY.

    Global zero modes are excluded, not lifted by a fictitious oscillator
    frequency. Report transverse vacuum factors rather than a complete
    finite-volume charged-particle matrix element or a quasiparticle pole.
    The Gamma hopping phases are NOT replaced with these positive factors.
    """
    assert U > 0 and K > 0
    rows, maximum_residual = [], 0.
    pairs = list(combinations(range(6), 2))
    straight = [z for z, (a, b) in enumerate(pairs) if a//2 == b//2]
    turns = [z for z in range(15) if z not in straight]
    for N in mesh_sizes:
        variances, flux, vacuum_energy = np.zeros(15), np.zeros(23), 0.
        kval = 2*np.pi*np.arange(N)/N
        xy = np.array(np.meshgrid(kval, kval, indexing='ij')).reshape(2, -1).T
        for kz in kval:
            ks = np.column_stack([xy, np.full(len(xy), kz)])
            B, C = _native_rotor_bloch(ks)
            residual = float(np.max(abs(C @ B.conj().swapaxes(1, 2))))
            maximum_residual = max(maximum_residual, residual)
            assert residual < 1e-12
            c = 1+np.exp(-1j*ks)
            lap_formula = 12*np.eye(3)[None, :, :]-c.conj()[:, :, None]*c[:, None, :]
            assert np.max(abs(B @ B.conj().swapaxes(1, 2)-lap_formula)) < 1e-12
            D = C.conj().swapaxes(1, 2) @ C
            w, v = np.linalg.eigh(D)
            assert np.min(w) > -1e-10
            active = w > 1e-9
            roots = np.sqrt(np.maximum(w, 0))
            inverse = np.divide(1, roots, out=np.zeros_like(w), where=active)
            cov = .5*np.sqrt(U/K)*((v*inverse[:, None, :]) @ v.conj().swapaxes(1, 2))
            variances += np.sum(np.real(np.diagonal(cov, axis1=1, axis2=2)), axis=0)/N**3
            flux += np.sum(np.real(np.diagonal(C @ cov @ C.conj().swapaxes(1, 2),
                                               axis1=1, axis2=2)), axis=0)/N**3
            vacuum_energy += .5*np.sqrt(U*K)*np.sum(np.where(active, roots, 0))/N**3
        assert abs(K*np.sum(flux)-vacuum_energy) < 1e-10
        corrections = 1-2*(-np.expm1(-flux/2))/flux
        overlaps = np.exp(-variances/2)
        rows.append(dict(mesh=N, zero_point_energy_per_cell=float(vacuum_energy),
                         triangle_flux_variance_min=float(min(flux[:20])),
                         triangle_flux_variance_max=float(max(flux[:20])),
                         square_flux_variance=float(np.mean(flux[20:])),
                         max_cosine_expectation_relative_correction=float(max(corrections)),
                         turn_transverse_overlap=float(np.mean(overlaps[turns])),
                         straight_transverse_overlap=float(np.mean(overlaps[straight])),
                         turn_conditional_hop_magnitude=float(abs(J)*np.mean(overlaps[turns])),
                         straight_conditional_hop_magnitude=float(abs(J)*np.mean(overlaps[straight]))))
    probes = []
    for kx in (.001, .01):
        _, C = _native_rotor_bloch([[kx, 0, 0]])
        w = np.linalg.eigvalsh(C[0].conj().T @ C[0])
        pos = w[w > 1e-10]
        assert len(pos) == 12
        probes.append(dict(kx=kx, lowest_two_speed_squared=(U*K*pos[:2]/kx**2).tolist()))
    return dict(scope='Noncompact Gaussian rotor calculation; f=1, no quantum slow-m dynamics',
                divergence_curl_max_residual=maximum_residual,
                rows=rows, transverse_speed_squared_probes=probes,
                predicted_speed_squared=U*K/5,
                omitted=['Compact nonperturbative flux processes', 'Global zero-mode matching',
                         'Quantum m fluctuations', 'Full particle self-energy and Weyl spectrum'],
                compact_error_bound_claimed=False)


