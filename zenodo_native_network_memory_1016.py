def _single_charge_core_geometry(shape, q_seed):
    """Local core function on a repeated candidate, without a charged torus ansatz.

    A single-endpoint value is only a local contribution. Physical periodic
    states need a second, compensating endpoint; core({i:-1,j:1}) is neutral.
    q_seed maps edges of the 4x4x4 reference cell to their integer charges.
    """
    vertices=list(product(*(range(s) for s in shape)))
    edges=[(v,a) for v in vertices for a in range(3)]
    index={e:i for i,e in enumerate(edges)}
    q=np.array([q_seed[(tuple(x%4 for x in v),a)] for v,a in edges])
    masks=[0]*len(edges);boundaries=[]
    def shift(v,a):
        w=list(v);w[a]=(w[a]+1)%shape[a];return tuple(w)
    for v in vertices:
        for a,b in combinations(range(3),2):
            bd=[index[e] for e in ((v,a),(shift(v,b),a),(v,b),(shift(v,a),b))]
            bit=1<<len(boundaries);boundaries.append(bd)
            for i in bd:masks[i]|=bit
    sy0=0
    for qi,mask in zip(q,masks):
        if qi%2:sy0^=mask
    assert all(int(sy0&mask==mask)==q[i]**2 for i,mask in enumerate(masks))
    affected=[{e for f,bd in enumerate(boundaries) if (mask>>f)&1 for e in bd} for mask in masks]
    def core(changes):
        sy=sy0;targets=set()
