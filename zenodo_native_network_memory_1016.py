def _single_charge_gamma_frames(lay,q,spectator,root,reverse=False):
    """Exact Gamma matrix elements in the selected neutral two-endpoint sector.

    A -1 deviation is pinned at spectator, the +1 deviation can move anywhere
    else. The full Pauli algebra, including all phases, is retained.
    """
    from collections import deque
    nq=2*lay['L']**3;sy=0
    for qi,mask in zip(q,lay['edge_faces']):
        if qi%2:sy^=mask
    sy^=lay['edge_faces'][spectator]^lay['edge_faces'][root]
    stabilizers=[((-1 if (sy>>i)&1 else 1)*p[0],p[1],p[2]) for i,p in enumerate(lay['stabilizers'])]+lay['straight']
    basis,bad=signed_basis(stabilizers,nq)
    assert not bad and len(basis)==nq
    def dagger(p):
        return (complex(p[0]).conjugate()*(-1 if (p[1]&p[2]).bit_count()%2 else 1),p[1],p[2])
    def value(p):
        while p[1] or p[2]:
            key=(p[1]|(p[2]<<nq)).bit_length()-1
            assert key in basis, 'Unfixed Gamma logical channel'
            p=multiply(p,basis[key])
        return p[0]
    adj=[[] for _ in q]
    for (v,a,b),(i,j) in zip(lay['links'],lay['endpoints']):
        if spectator in (i,j):continue
        op=lay['geo']['embed'](v,a,b);adj[i].append((j,op));adj[j].append((i,op))
    frames={root:(1,0,0)};queue=deque([root])
    while queue:
        i=queue.popleft()
        for j,op in (adj[i][::-1] if reverse else adj[i]):
            if j not in frames:frames[j]=multiply(op,frames[i]);queue.append(j)
    assert len(frames)==len(q)-1
    phases=np.zeros((len(q),len(q)),complex)
    for i in frames:
        for j,op in adj[i]:
            phases[j,i]=value(multiply(dagger(frames[j]),multiply(op,frames[i])))
    assert np.max(abs(phases-phases.conj().T))==0
    return phases,frames,value,dagger


def _single_charge_periodic_hopping(lay,q,twists=(1,1,1)):
    """Periodic scalar gauge inferred from local Gamma holonomies.

    beta_(v,a)=(-1)^(sum_(b<a) v_b + n_(v,a)); product_boundary beta=-F_p.
    alpha_(v,+a)=1, alpha_(v,-a)=beta_(v-a,a).
    For canonical ports a<b: u_(b,a)=-i alpha_a alpha_b.
    Global twists label flat boundary holonomies. Checked against exact Pauli
    matrix elements with a pinned compensating endpoint by the public audit.
    """
    L=lay['L'];index={e:i for i,e in enumerate(lay['edge_keys'])};n=q*q
    u=np.zeros((len(q),len(q)),complex)
    for (v,a,b),(i,j) in zip(lay['links'],lay['endpoints']):
        half=[]
        for port in (a,b):
            axis=port//2
            if port%2:
                w=list(v);w[axis]=(w[axis]-1)%L;w=tuple(w)
                sign=(-1)**(sum(w[:axis])+int(n[index[(w,axis)]]))
                sign*=twists[axis] if w[axis]==L-1 else 1
            else:sign=1
            half.append(sign)
        u[j,i]=-1j*half[0]*half[1];u[i,j]=u[j,i].conjugate()
    return u


